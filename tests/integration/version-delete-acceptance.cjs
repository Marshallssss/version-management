const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const admin = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const page = await admin.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const post = async (url, data, client = admin.request) => {
    const response = await client.post(url, { data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), url + ': ' + await response.text())
    return response.status() === 204 ? null : response.json()
  }
  const remove = (id, reason, key = randomUUID(), client = admin.request) => client.delete('/api/v1/component-versions/' + id, { data: { reason }, headers: { 'Idempotency-Key': key } })
  let project
  try {
    await post('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    project = await post('/api/v1/projects', { code: 'DELETE-V-' + randomUUID().slice(0, 8), name: '版本删除验收', reason: '自动化验收' })
    const component = await post(`/api/v1/projects/${project.id}/components`, { name: '主控程序', reason: '自动化验收' })
    const createVersion = (number, maturity = 'Released') => post(`/api/v1/components/${component.id}/versions`, { versionNumber: number, maturity, reason: '版本删除验收' })
    const kept = await createVersion('V1-keep')
    const deletable = await createVersion('V2-delete')
    await post(`/api/v1/component-versions/${deletable.id}/patches`, { patchCode: 'HF-1', title: '误录补丁', issueDescription: '测试问题', resolutionDescription: '测试修复', status: 'Released' })
    await post(`/api/v1/component-versions/${deletable.id}/recommend`, { state: '', reason: '推荐清理验收' })
    assert.equal((await remove(deletable.id, '')).status(), 400)
    assert.equal((await remove(deletable.id, 'x'.repeat(501))).status(), 400)
    assert.equal((await admin.request.delete(`/api/v1/component-versions/${deletable.id}`, { data: { reason: '缺少幂等键' } })).status(), 400)
    for (const role of ['Admin', 'SeniorEngineer', 'Engineer', 'Viewer']) {
      const userName = role.toLowerCase() + '-' + randomUUID().slice(0, 8)
      const password = randomUUID()
      await post('/api/v1/admin/users', { userName, displayName: '权限验收', password, role, reason: '权限验收' })
      const other = await browser.newContext({ baseURL })
      await post('/api/v1/auth/login', { userName, password }, other.request)
      if (role !== 'Admin') assert.equal((await remove(deletable.id, '权限测试', randomUUID(), other.request)).status(), 403)
      if (role === 'Admin') {
        const otherPage = await other.newPage()
        await otherPage.goto('/')
        await otherPage.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
        await otherPage.reload()
        await otherPage.locator('.nav-item').filter({ hasText: '版本' }).click()
        await otherPage.locator('.root-node').first().click()
        assert(await otherPage.locator('.version-delete-button').count() > 0)
        const adminVersion = await createVersion('V-admin-delete')
        assert.equal((await remove(adminVersion.id, '管理员清理误登记', randomUUID(), other.request)).status(), 200)
      }
      await other.close()
    }
    const key = randomUUID()
    const responses = await Promise.all([remove(deletable.id, '并发删除验收', key), remove(deletable.id, '并发删除验收', key)])
    for (const response of responses) assert.equal(response.status(), 200, await response.text())
    assert.equal((await remove(deletable.id, '并发删除验收', key)).status(), 200)
    assert.equal((await remove(deletable.id, '不同请求', key)).status(), 409)
    assert.equal((await admin.request.get(`/api/v1/component-versions/${deletable.id}`)).status(), 404)
    const audit = await (await admin.request.get('/api/v1/audit?entityId=' + deletable.id)).json()
    const deletionAudit = audit.filter(item => item.action === 'ComponentVersionDeleted')
    assert.equal(deletionAudit.length, 1)
    assert(deletionAudit[0].actor && deletionAudit[0].correlationId)
    const uiVersion = await createVersion('V3-ui-delete', 'Testing')
    await post(`/api/v1/component-versions/${uiVersion.id}/patches`, { patchCode: 'HF-UI', title: '界面清理验收', issueDescription: '测试问题', resolutionDescription: '测试修复', status: 'Draft' })
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: '版本' }).click()
    await page.locator('.root-node').first().click()
    await page.getByRole('button', { name: '删除版本 V3-ui-delete', exact: true }).click()
    let dialog = page.getByRole('dialog')
    assert(await dialog.getByRole('button', { name: '确认删除版本' }).isDisabled())
    await dialog.getByRole('button', { name: /取\s*消/ }).click()
    assert.equal((await admin.request.get(`/api/v1/component-versions/${uiVersion.id}`)).status(), 200)
    await page.getByRole('button', { name: '删除版本 V3-ui-delete', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('删除原因').fill('删除误登记版本')
    const output = path.resolve('artifacts/version-delete')
    mkdirSync(output, { recursive: true })
    await page.evaluate(async () => { await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); await Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))) })
    await page.screenshot({ path: path.join(output, 'confirm-desktop.png') })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.evaluate(async () => { await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); await Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))) })
    const box = await dialog.boundingBox()
    assert(box && box.x >= 0 && box.x + box.width <= 391, 'Mobile confirmation dialog must fit in the viewport')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.screenshot({ path: path.join(output, 'confirm-mobile.png') })
    await dialog.getByRole('button', { name: '确认删除版本' }).click()
    await page.getByRole('button', { name: '删除版本 V3-ui-delete', exact: true }).waitFor({ state: 'detached' })
    const after = await (await admin.request.get('/api/v1/projects/' + project.id)).json()
    assert.equal(after.components.length, 1)
    assert.deepEqual(after.components[0].versions.map(version => version.id), [kept.id])
    assert.equal((await admin.request.get(`/api/v1/component-versions/${uiVersion.id}`)).status(), 404)
    const baseline = await post(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'S', baselineCode: 'PROTECTED', reason: '引用保护验收' })
    const snapshot = await (await admin.request.get('/api/v1/baselines/' + baseline.id)).json()
    assert.equal((await remove(kept.id, '基线引用保护')).status(), 409)
    assert.deepEqual((await (await admin.request.get('/api/v1/baselines/' + baseline.id)).json()).items, snapshot.items)
    const historical = await createVersion('V4-history')
    const machine = await post('/api/v1/machines', { projectId: project.id, serialNumber: 'DELETE-V-' + randomUUID().slice(0, 8), name: '历史保护机台', reason: '验收' })
    for (const versionId of [historical.id, kept.id]) await post(`/api/v1/machines/${machine.id}/facts`, { operationType: 'Observation', coverage: 'Partial', sourceType: 'Manual', reason: '历史保护', items: [{ componentId: component.id, versionId, absent: false, knownInstalledAt: null }] })
    assert.equal((await remove(historical.id, '历史引用保护')).status(), 409)
    const blocked = await createVersion('V5-exposure')
    await post(`/api/v1/component-versions/${blocked.id}/safety`, { state: 'Blocked', reason: '影响快照保护' })
    assert.equal((await remove(blocked.id, '影响快照保护')).status(), 409)
    assert.deepEqual(errors, [])
    console.log('Version deletion acceptance passed: Admin/SuperAdmin UI/API, Engineer/Viewer denial, confirmation/cancel, concurrent replay, audit, related-record cleanup, sibling retention and historical references.')
  } finally {
    if (project) await post(`/api/v1/projects/${project.id}/archive`, { reason: '验收结束' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
