const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1366, height: 900 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const output = path.resolve('artifacts/operation-impact')
  mkdirSync(output, { recursive: true })
  const write = async (url, data, method = 'post', client = context.request) => {
    const response = await client[method](url, { data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), url + ': ' + await response.text())
    return response.status() === 204 || !(await response.text()) ? null : response.json()
  }
  const read = async url => {
    const response = await context.request.get(url)
    assert(response.ok(), url + ': ' + await response.text())
    return response.json()
  }
  let project
  const machines = []
  let releaseImpact
  const openProject = async (target = page) => {
    await target.goto('/')
    await target.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await target.reload()
    await target.locator('.nav-item').filter({ hasText: /^版本$/ }).click()
    await target.locator('.root-node').first().click()
  }
  const openDelete = async number => {
    await page.getByRole('navigation', { name: '版本管理' }).getByRole('button', { name: '版本', exact: true }).click()
    await page.getByRole('button', { name: `删除版本 ${number}`, exact: true }).click()
    const dialog = page.locator('.version-delete-dialog')
    await dialog.waitFor({ state: 'visible' })
    return dialog
  }
  const ready = dialog => dialog.locator('.operation-impact-preview[aria-busy="false"]').waitFor()
  const cancel = async dialog => {
    await dialog.getByRole('button', { name: /取\s*消/ }).click()
    await dialog.waitFor({ state: 'hidden' })
  }
  const expand = async (dialog, label) => {
    const details = dialog.locator('details').filter({ has: page.locator('summary').filter({ hasText: label }) })
    await details.waitFor()
    if (!(await details.evaluate(element => element.open))) await details.locator('summary').click()
    return details
  }
  const capture = async (dialog, name) => {
    await page.evaluate(async () => {
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
      await Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {})))
    })
    const box = await dialog.boundingBox()
    assert(box && box.x >= -1 && box.x + box.width <= page.viewportSize().width + 1, name + ': dialog exceeds viewport width')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), name + ': page overflow')
    assert(!/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i.test(await dialog.innerText()), name + ': internal GUID exposed')
    await page.screenshot({ path: path.join(output, name + '.png') })
  }
  const selectBaseline = async code => {
    await page.locator('.nav-item').filter({ hasText: '基线' }).click()
    await page.locator('.baseline-timeline button').filter({ hasText: code }).click()
    await page.locator('.baseline-snapshot h3').filter({ hasText: code }).waitFor()
  }
  const failedPreviewAndRecovery = async ({ dialog, recordUrl, writeUrl, confirmText, openPreview }) => {
    const original = await read(recordUrl)
    const impactPath = recordUrl + '/operation-impact'
    const pattern = '**' + impactPath
    let writes = 0
    const trackWrite = request => { if (request.method() !== 'GET' && new URL(request.url()).pathname === writeUrl) writes++ }
    const failImpact = route => route.fulfill({ status: 500, contentType: 'application/problem+json', body: JSON.stringify({ title: '影响预览暂时不可用，请重试。' }) })
    page.on('request', trackWrite)
    await page.route(pattern, failImpact)
    try {
      await openPreview()
      await dialog.locator('.operation-impact-preview [role="alert"]').waitFor({ timeout: 20000 })
      assert(await dialog.getByRole('button', { name: confirmText, exact: true }).isDisabled(), confirmText + ': a failed preview must block even previously cached permission')
      assert.equal(writes, 0, confirmText + ': preview failure must not send a write request')
      assert.deepEqual(await read(recordUrl), original, confirmText + ': failure must not alter the record')
      await page.unroute(pattern, failImpact)
      const refreshed = page.waitForResponse(response => new URL(response.url()).pathname === impactPath && response.request().method() === 'GET' && response.ok())
      await dialog.getByRole('button', { name: '刷新影响预览' }).click()
      await refreshed
      await dialog.getByRole('button', { name: confirmText, exact: true }).click({ trial: true })
      await ready(dialog)
      assert.equal(await dialog.locator('.operation-impact-preview [role="alert"]').count(), 0)
      assert.equal(writes, 0, confirmText + ': recovery must wait for explicit confirmation before writing')
      assert.deepEqual(await read(recordUrl), original, confirmText + ': refreshing the preview must not alter the record')
    } finally {
      await page.unroute(pattern, failImpact)
      page.off('request', trackWrite)
    }
  }
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    assert.equal((await read('/api/v1/maintenance-capabilities')).enabled, true, 'Run this suite against the enabled-maintenance development Host')
    const suffix = randomUUID().slice(0, 8)
    project = await write('/api/v1/projects', { code: 'IMPACT-UI-' + suffix, name: '操作影响确认验收', reason: '自动化验收' })
    const component = await write(`/api/v1/projects/${project.id}/components`, { name: '主控程序', reason: '自动化验收' })
    const version = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V1-frozen', maturity: 'Released', reason: '自动化验收' })
    const baseline = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'FROZEN', baselineCode: '冻结历史基线', publishImmediately: true, reason: '冻结验收' })
    const snapshot = await read(`/api/v1/baselines/${baseline.id}`)
    const replacement = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V2-replacement', maturity: 'Released', reason: '自动化验收' })
    const removable = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V3-removable', maturity: 'Draft', reason: '自动化验收' })
    await write(`/api/v1/component-versions/${removable.id}/patches`, { patchCode: 'HF.1', title: '可清理补丁', issueDescription: '误登记', resolutionDescription: '尚未部署', status: 'Draft' })
    const machine = await write('/api/v1/machines', { projectId: project.id, serialNumber: 'IMPACT-A-' + suffix, name: '影响预览运行机台', stage: 'Lab', owner: '验收人员', chambers: [{ number: 1, stage: 'Lab' }], reason: '自动化验收' })
    machines.push(machine.id)
    const retired = await write('/api/v1/machines', { projectId: project.id, serialNumber: 'IMPACT-B-' + suffix, name: '已删除历史机台', reason: '自动化验收' })
    machines.push(retired.id)
    for (const item of [machine, retired]) {
      await write(`/api/v1/machines/${item.id}/facts`, { operationType: 'InitialSnapshot', coverage: 'Full', sourceType: 'Manual', reason: '引用记录', items: [{ componentId: component.id, versionId: version.id, absent: false, knownInstalledAt: null }] })
    }
    await write(`/api/v1/machines/${machine.id}/chambers/1/configuration`, { items: [{ componentId: component.id, versionId: version.id }], reason: 'PM 引用记录' }, 'put')
    await write(`/api/v1/machines/${machine.id}/target`, { configurationBaselineId: baseline.id, reason: '目标引用记录' })
    await write(`/api/v1/machines/${retired.id}`, { reason: '删除测试机台，保留历史' }, 'delete')

    await openProject()
    let dialog = await openDelete('V1-frozen')
    await ready(dialog)
    await dialog.getByLabel('删除原因').fill('检查引用后决定')
    assert(await dialog.getByRole('button', { name: '确认删除版本' }).isDisabled(), 'Referenced version deletion must be blocked')
    assert((await dialog.innerText()).includes('存在受保护引用'))
    const historyReferences = await expand(dialog, '整机配置历史')
    const deletedRow = historyReferences.locator('li').filter({ hasText: '已删除历史机台' })
    assert((await deletedRow.innerText()).includes('已删除'))
    assert.equal(await deletedRow.locator('.impact-reference-link').count(), 0, 'Deleted machine must not have an active link')
    await capture(dialog, 'protected-version-desktop')
    await page.setViewportSize({ width: 390, height: 844 })
    await capture(dialog, 'protected-version-mobile')
    await page.setViewportSize({ width: 1366, height: 900 })
    const baselines = await expand(dialog, '引用基线')
    await baselines.getByRole('button', { name: '冻结历史基线', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.locator('.baseline-snapshot h3').filter({ hasText: '冻结历史基线' }).waitFor()
    assert.deepEqual((await read(`/api/v1/baselines/${baseline.id}`)).items, snapshot.items)

    await page.locator('.nav-item').filter({ hasText: /^版本$/ }).click()
    await page.locator('.root-node').first().click()
    dialog = await openDelete('V1-frozen')
    await ready(dialog)
    const currentMachines = await expand(dialog, '整机当前配置')
    await currentMachines.getByRole('button', { name: '影响预览运行机台', exact: true }).click()
    await page.locator('.machine-detail-header').filter({ hasText: '影响预览运行机台' }).waitFor()

    await openProject()
    const impactPattern = `**/component-versions/${removable.id}/operation-impact`
    const gate = new Promise(resolve => { releaseImpact = resolve })
    await page.route(impactPattern, async route => { await gate; await route.continue() })
    dialog = await openDelete('V3-removable')
    await dialog.getByLabel('删除原因').fill('安全检查完成后删除')
    await dialog.locator('.operation-impact-preview[aria-busy="true"]').waitFor()
    assert(await dialog.getByRole('button', { name: '确认删除版本' }).isDisabled(), 'Loading impact must not permit deletion')
    releaseImpact()
    await ready(dialog)
    await page.unroute(impactPattern)
    await cancel(dialog)
    assert.equal((await read(`/api/v1/component-versions/${removable.id}`)).version.versionNumber, 'V3-removable')

    await page.route(impactPattern, route => route.fulfill({ status: 500, contentType: 'application/problem+json', body: JSON.stringify({ title: '影响预览暂时不可用，请重试。' }) }))
    dialog = await openDelete('V3-removable')
    await dialog.getByLabel('删除原因').fill('失败不可提交')
    await dialog.locator('.operation-impact-preview [role="alert"]').waitFor({ timeout: 20000 })
    assert(await dialog.getByRole('button', { name: '确认删除版本' }).isDisabled(), 'Failed impact must not permit deletion')
    await page.unroute(impactPattern)
    await dialog.getByRole('button', { name: '刷新影响预览' }).click()
    await dialog.getByRole('button', { name: '确认删除版本' }).click({ trial: true })
    await ready(dialog)
    assert(!(await dialog.getByRole('button', { name: '确认删除版本' }).isDisabled()))
    assert((await dialog.innerText()).includes('1 条补丁'))
    await dialog.getByRole('button', { name: '确认删除版本' }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal((await context.request.get(`/api/v1/component-versions/${removable.id}`)).status(), 404)

    const originalVersionDetail = await read(`/api/v1/component-versions/${version.id}`)
    const releasedTransitions = detail => detail.transitions.filter(item => item.axis === 'Maturity' && item.toState === 'Released').map(item => ({ id: item.id, occurredAt: item.occurredAt }))
    await page.locator('.version-item').filter({ hasText: 'V1-frozen' }).click()
    await page.getByRole('button', { name: '调测维护', exact: true }).click()
    const versionForm = page.locator('.version-maintenance form')
    await versionForm.getByLabel('版本号', { exact: true }).fill('V1-corrected')
    await versionForm.locator('select').selectOption('Maintenance')
    await versionForm.getByLabel('维护原因').fill('修正误登记版本号')
    await versionForm.getByRole('button', { name: '保存调测修改' }).click()
    dialog = page.locator('.version-maintenance-dialog')
    await ready(dialog)
    assert((await dialog.locator('.operation-change-list').innerText()).includes('V1-frozen → V1-corrected'))
    await capture(dialog, 'version-maintenance-desktop')
    await page.setViewportSize({ width: 390, height: 844 })
    await capture(dialog, 'version-maintenance-mobile')
    await page.setViewportSize({ width: 1366, height: 900 })
    await cancel(dialog)
    assert.equal(await versionForm.getByLabel('版本号', { exact: true }).inputValue(), 'V1-corrected', 'Cancel preserves the draft')
    assert.equal((await read(`/api/v1/component-versions/${version.id}`)).version.versionNumber, 'V1-frozen', 'Preview and cancel must not write')
    await failedPreviewAndRecovery({ dialog, recordUrl: `/api/v1/component-versions/${version.id}`, writeUrl: `/api/v1/component-versions/${version.id}/maintenance`, confirmText: '确认维护版本', openPreview: () => versionForm.getByRole('button', { name: '保存调测修改' }).click() })
    await dialog.getByRole('button', { name: '确认维护版本', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    const updatedVersionDetail = await read(`/api/v1/component-versions/${version.id}`)
    assert.equal(updatedVersionDetail.version.versionNumber, 'V1-corrected')
    assert.equal(updatedVersionDetail.version.maturity, 'Maintenance')
    assert.equal(updatedVersionDetail.version.createdAt, originalVersionDetail.version.createdAt, 'Editing name or maturity must preserve unedited registration timestamp precision')
    assert.deepEqual(releasedTransitions(updatedVersionDetail), releasedTransitions(originalVersionDetail), 'Editing name or maturity must preserve the original release timestamp')
    assert.deepEqual((await read(`/api/v1/baselines/${baseline.id}`)).items, snapshot.items, 'Version maintenance preserves frozen baseline labels')

    await selectBaseline('冻结历史基线')
    await page.getByRole('button', { name: '历史维护', exact: true }).click()
    const baselineForm = page.locator('.maintenance-action form')
    const originalTimeInput = await baselineForm.getByLabel('发布时间', { exact: true }).inputValue()
    await baselineForm.locator('.baseline-selection-list select').selectOption(replacement.id)
    await baselineForm.getByLabel('维护原因').fill('补录已评审的历史版本')
    const actualBefore = await read(`/api/v1/machines/${machine.id}/configuration`)
    await baselineForm.getByRole('button', { name: '保存历史维护数据' }).click()
    dialog = page.locator('.baseline-operation-dialog')
    await ready(dialog)
    assert((await dialog.locator('.operation-changes').innerText()).includes('V1-frozen'))
    assert((await dialog.locator('.operation-changes').innerText()).includes('V2-replacement'))
    await capture(dialog, 'baseline-maintenance-desktop')
    await page.setViewportSize({ width: 390, height: 844 })
    await capture(dialog, 'baseline-maintenance-mobile')
    await cancel(dialog)
    assert.equal(await baselineForm.getByLabel('发布时间', { exact: true }).inputValue(), originalTimeInput)
    assert.equal(await baselineForm.locator('.baseline-selection-list select').inputValue(), replacement.id, 'Cancel keeps the selected replacement version')
    assert.deepEqual((await read(`/api/v1/baselines/${baseline.id}`)).items, snapshot.items, 'History confirmation must not save before approval')
    await failedPreviewAndRecovery({ dialog, recordUrl: `/api/v1/baselines/${baseline.id}`, writeUrl: `/api/v1/baselines/${baseline.id}/maintenance`, confirmText: '确认维护基线', openPreview: () => baselineForm.getByRole('button', { name: '保存历史维护数据' }).click() })
    await dialog.getByRole('button', { name: '确认维护基线' }).click()
    await dialog.waitFor({ state: 'hidden' })
    const maintained = await read(`/api/v1/baselines/${baseline.id}`)
    assert.equal(maintained.baseline.state, 'Released')
    assert.equal(maintained.items.find(item => item.componentId === component.id).versionId, replacement.id)
    assert.equal(maintained.baseline.createdAt, snapshot.baseline.createdAt, 'Changing only component versions must preserve baseline recording timestamp precision')
    assert.equal(maintained.baseline.releasedAt, snapshot.baseline.releasedAt, 'Changing only component versions must preserve release timestamp precision')
    assert.deepEqual(await read(`/api/v1/machines/${machine.id}/configuration`), actualBefore, 'Baseline maintenance must not rewrite machine actual facts')

    await page.getByRole('button', { name: '历史维护', exact: true }).click()
    await baselineForm.getByLabel('发布时间', { exact: true }).fill('2020-02-03T08:30')
    await baselineForm.getByLabel('维护原因').fill('明确修正历史发布时间')
    await baselineForm.getByRole('button', { name: '保存历史维护数据' }).click()
    await ready(dialog)
    await dialog.locator('.operation-time-change').waitFor()
    assert.equal(await dialog.locator('.operation-changes').count(), 0, 'Time-only maintenance must not imply component changes')
    await dialog.getByRole('button', { name: '确认维护基线' }).click()
    await dialog.waitFor({ state: 'hidden' })
    const backdated = await read(`/api/v1/baselines/${baseline.id}`)
    assert.equal(new Date(backdated.baseline.releasedAt).getTime(), new Date('2020-02-03T08:30').getTime())
    assert.equal(backdated.baseline.createdAt, snapshot.baseline.createdAt, 'Backdating release must preserve actual creation time')
    assert.equal(backdated.baseline.releaseRecordedAt, snapshot.baseline.releaseRecordedAt, 'Backdating release must preserve actual release action time')
    assert.deepEqual(backdated.items, maintained.items)
    assert.deepEqual(await read(`/api/v1/machines/${machine.id}/configuration`), actualBefore)

    await page.setViewportSize({ width: 1366, height: 900 })
    // Create fresh records here so the real three-minute withdrawal window is not timing-sensitive.
    const protectedBaseline = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'TARGET', baselineCode: '目标引用不可撤回', publishImmediately: true, reason: '撤回阻断验收' })
    await write(`/api/v1/machines/${machine.id}/target`, { configurationBaselineId: protectedBaseline.id, reason: '保护目标基线' })
    const withdrawable = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'UNDO', baselineCode: '未引用可撤回', publishImmediately: true, reason: '撤回验收' })
    const withdrawSnapshot = await read(`/api/v1/baselines/${withdrawable.id}`)
    await openProject()
    await selectBaseline('目标引用不可撤回')
    await page.locator('.baseline-undo').getByLabel('撤回原因').fill('有目标引用时应阻止')
    await page.getByRole('button', { name: '撤回已发布基线', exact: true }).click()
    dialog = page.locator('.baseline-operation-dialog')
    await ready(dialog)
    assert(await dialog.getByRole('button', { name: '确认撤回基线' }).isDisabled())
    assert((await dialog.innerText()).includes('机台目标记录'))
    await capture(dialog, 'protected-withdrawal-desktop')
    await cancel(dialog)
    assert.equal((await read(`/api/v1/baselines/${protectedBaseline.id}`)).baseline.state, 'Released')
    await selectBaseline('未引用可撤回')
    await page.locator('.baseline-undo').getByLabel('撤回原因').fill('撤回误发布记录')
    await page.getByRole('button', { name: '撤回已发布基线', exact: true }).click()
    await ready(dialog)
    assert(!(await dialog.getByRole('button', { name: '确认撤回基线' }).isDisabled()))
    await cancel(dialog)
    assert.equal((await read(`/api/v1/baselines/${withdrawable.id}`)).baseline.state, 'Released')
    await failedPreviewAndRecovery({ dialog, recordUrl: `/api/v1/baselines/${withdrawable.id}`, writeUrl: `/api/v1/baselines/${withdrawable.id}/withdraw-release`, confirmText: '确认撤回基线', openPreview: () => page.getByRole('button', { name: '撤回已发布基线', exact: true }).click() })
    await dialog.getByRole('button', { name: '确认撤回基线' }).click()
    await dialog.waitFor({ state: 'hidden' })
    const withdrawn = await read(`/api/v1/baselines/${withdrawable.id}`)
    assert.equal(withdrawn.baseline.state, 'Deprecated')
    assert.deepEqual(withdrawn.items, withdrawSnapshot.items, 'Withdrawal preserves frozen items')
    assert.equal((await read(`/api/v1/component-versions/${replacement.id}`)).version.maturity, 'Released')

    const userName = 'impact-viewer-' + suffix
    const password = randomUUID()
    await write('/api/v1/admin/users', { userName, displayName: '影响预览只读验收', password, role: 'Viewer', reason: '权限验收' })
    const viewer = await browser.newContext({ baseURL })
    try {
      await write('/api/v1/auth/login', { userName, password }, 'post', viewer.request)
      const viewerPage = await viewer.newPage()
      viewerPage.on('pageerror', error => errors.push(error.message))
      await openProject(viewerPage)
      assert.equal(await viewerPage.locator('.version-delete-button').count(), 0)
      await viewerPage.locator('.version-item').filter({ hasText: 'V1-corrected' }).click()
      assert.equal(await viewerPage.getByRole('button', { name: '调测维护', exact: true }).count(), 0)
      await viewerPage.locator('.nav-item').filter({ hasText: '基线' }).click()
      await viewerPage.locator('.baseline-timeline button').filter({ hasText: '目标引用不可撤回' }).click()
      assert.equal(await viewerPage.getByRole('button', { name: '历史维护', exact: true }).count(), 0)
      assert.equal(await viewerPage.getByRole('button', { name: '撤回已发布基线', exact: true }).count(), 0)
      assert.equal((await viewer.request.get(`/api/v1/component-versions/${version.id}/operation-impact`)).status(), 403)
      assert.equal((await viewer.request.get(`/api/v1/baselines/${baseline.id}/operation-impact`)).status(), 403)
    } finally { await viewer.close() }
    assert.deepEqual(errors, [])
    console.log('Operation impact UI acceptance passed: protected references/navigation, deletion/version maintenance/baseline maintenance/withdrawal preview failure and recovery without writes, confirmed operations, frozen snapshots, unchanged machine facts, Viewer permissions and desktop/mobile dialogs.')
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
    throw error
  } finally {
    releaseImpact?.()
    await page.unrouteAll({ behavior: 'ignoreErrors' }).catch(() => {})
    for (const machineId of machines) await write(`/api/v1/machines/${machineId}`, { reason: '验收完成清理' }, 'delete').catch(() => {})
    if (project) await write(`/api/v1/projects/${project.id}/archive`, { reason: '验收完成归档' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error.stack || error.message); process.exitCode = 1 })
