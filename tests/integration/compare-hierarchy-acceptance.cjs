const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const output = path.resolve('artifacts/compare-hierarchy')
  mkdirSync(output, { recursive: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const reason = '配置对比组件层级自动验收'
  const write = async (url, data, method = 'POST', request = context.request) => {
    const response = await request.fetch(url, { method, data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), `${url}: ${await response.text()}`)
    return response.status() === 204 ? null : response.json()
  }
  const get = async url => {
    const response = await context.request.get(url)
    assert(response.ok(), `${url}: ${await response.text()}`)
    return response.json()
  }
  const openCompare = async (targetPage, projectId) => {
    await targetPage.goto('/')
    await targetPage.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), projectId)
    await targetPage.reload()
    await targetPage.locator('.nav-item').filter({ hasText: '配置比对' }).click()
    await targetPage.getByLabel('左侧配置', { exact: true }).waitFor()
  }
  const selectSide = async (side, kind, id, targetPage = page) => {
    await targetPage.getByRole('group', { name: `${side}类型`, exact: true }).getByRole('button', { name: kind, exact: true }).click()
    const select = targetPage.getByLabel(`${side}配置`, { exact: true })
    await select.locator(`option[value="${id}"]`).waitFor({ state: 'attached' })
    await select.selectOption(id)
  }
  const whole = targetPage => targetPage.locator('#compare-whole-panel')
  const row = (panel, component) => panel.locator(`tbody tr[data-component-id="${component.id}"]`)
  const assertDepth = async (panel, component, expected) => {
    await row(panel, component).waitFor()
    assert.equal(await row(panel, component).getAttribute('data-depth'), String(expected), `${component.name} should have depth ${expected}`)
  }
  const assertRows = async (panel, components) => {
    await panel.locator('tbody tr').first().waitFor()
    assert.deepEqual(await panel.locator('tbody tr').evaluateAll(rows => rows.map(item => item.dataset.componentId)), components.map(item => item.id))
  }
  const screenshot = async (name, width, panel) => {
    await page.setViewportSize({ width, height: 1000 })
    await panel.scrollIntoViewIfNeeded()
    await page.evaluate(() => document.fonts.ready)
    await page.screenshot({ path: path.join(output, `${name}-${width}.png`), fullPage: true, animations: 'disabled' })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Page overflow at ${width}px`)
    for (const element of await panel.locator('th, td').all()) {
      assert(await element.evaluate(item => item.scrollWidth <= item.clientWidth + 2), `Clipped table content at ${width}px: ${await element.innerText()}`)
    }
  }
  let project
  let viewer
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    project = await write('/api/v1/projects', { code: 'COMPARETREE-' + randomUUID().slice(0, 8), name: '配置比对多层级自动验收', reason })
    const component = async (name, parent) => ({ ...await write(`/api/v1/projects/${project.id}/components`, { name, parentComponentId: parent?.id, reason }), name })
    const controls = await component('控制系统')
    const process = await component('工艺系统')
    const motion = await component('运动控制', controls)
    const servo = await component('伺服驱动模块', motion)
    const sensor = await component('传感器采集', controls)
    const gas = await component('气体流量控制器', process)
    await write(`/api/v1/components/${process.id}/reorder`, { direction: 'Up', reason })
    const version = async (item, number) => write(`/api/v1/components/${item.id}/versions`, { versionNumber: number, maturity: 'Released', reason })
    const servo1 = await version(servo, 'V1.0-control')
    const sensor1 = await version(sensor, 'V1.0-sensor')
    const gas1 = await version(gas, 'V1.0-flow')
    const baseline = async code => write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'TREE', baselineCode: code, publishImmediately: true, reason })
    const oldBaseline = await baseline('初始层级基线')
    const frozen = await get(`/api/v1/baselines/${oldBaseline.id}`)
    const servo2 = await version(servo, 'V2.0-control')
    const nextBaseline = await baseline('控制升级基线')
    const machines = []
    for (const [name, selectedServo] of [['原配置实验室机台', servo1], ['升级配置实验室机台', servo2]]) {
      const machine = await write('/api/v1/machines', { projectId: project.id, serialNumber: 'CT-' + randomUUID().slice(0, 8), name, stage: 'Lab', owner: '验收工程师', chambers: [{ number: 1, stage: 'Lab' }], reason })
      machines.push(machine)
      await write(`/api/v1/machines/${machine.id}/facts`, { operationType: 'InitialSnapshot', coverage: 'Full', sourceType: 'Manual', reason, items: [[servo, selectedServo], [sensor, sensor1], [gas, gas1]].map(([item, selected]) => ({ componentId: item.id, versionId: selected.id, absent: false, knownInstalledAt: null })) })
    }
    await write(`/api/v1/machines/${machines[0].id}/chambers/1/configuration`, { items: [{ componentId: servo.id, versionId: servo2.id }], reason }, 'PUT')

    await openCompare(page, project.id)
    await selectSide('左侧', '机台', machines[1].id)
    await selectSide('右侧', '基线', oldBaseline.id)
    let panel = whole(page)
    await assertRows(panel, [process, gas, controls, motion, servo, sensor])
    await assertDepth(panel, controls, 0)
    await assertDepth(panel, motion, 1)
    await assertDepth(panel, servo, 2)
    assert((await row(panel, controls).getAttribute('class')).includes('comparison-tree-context'), 'A versionless root must be a context row, not an empty version difference')
    assert((await row(panel, motion).getAttribute('class')).includes('comparison-tree-context'))
    assert((await row(panel, servo).innerText()).includes('V2.0-control'))
    assert((await row(panel, servo).innerText()).includes('V1.0-control'))
    await panel.getByRole('button', { name: '收起控制系统', exact: true }).click()
    await row(panel, servo).waitFor({ state: 'detached' })
    await assertRows(panel, [process, gas, controls])
    await panel.getByRole('button', { name: '展开控制系统', exact: true }).click()
    await assertDepth(panel, servo, 2)
    await page.getByRole('checkbox', { name: '只看差异', exact: true }).check()
    await row(panel, gas).waitFor({ state: 'detached' })
    await assertRows(panel, [controls, motion, servo])
    assert.equal(await row(panel, sensor).count(), 0, 'An unchanged sibling must not remain in differences-only mode')
    for (const width of [1440, 390]) await screenshot('machine-baseline-differences', width, panel)
    await page.setViewportSize({ width: 1440, height: 1000 })

    await page.getByRole('checkbox', { name: '只看差异', exact: true }).uncheck()
    await selectSide('左侧', '机台', machines[0].id)
    await page.getByRole('tab', { name: 'PM1', exact: true }).click()
    panel = page.locator('#compare-pm-1')
    await assertDepth(panel, servo, 2)
    assert((await row(panel, servo).locator('td').nth(0).innerText()).includes('PM 特例'))
    await page.getByRole('checkbox', { name: '只看差异', exact: true }).check()
    await assertRows(panel, [controls, motion, servo])
    await page.getByRole('button', { name: '交换左右配置', exact: true }).click()
    await panel.locator('thead').getByText('初始层级基线', { exact: false }).first().waitFor()
    await assertDepth(panel, servo, 2)
    assert((await row(panel, servo).locator('td').nth(0).innerText()).includes('V1.0-control'))
    assert((await row(panel, servo).locator('td').nth(1).innerText()).includes('PM 特例'))
    for (const width of [1440, 390]) await screenshot('pm-baseline-reversed', width, panel)
    await page.setViewportSize({ width: 1440, height: 1000 })

    await selectSide('左侧', '机台', machines[0].id)
    await selectSide('右侧', '机台', machines[1].id)
    await page.getByRole('tab', { name: '整机', exact: true }).click()
    panel = whole(page)
    await assertRows(panel, [controls, motion, servo])
    await assertDepth(panel, servo, 2)
    await selectSide('左侧', '基线', oldBaseline.id)
    await selectSide('右侧', '基线', nextBaseline.id)
    await page.getByRole('tab', { name: '基线', exact: true }).waitFor()
    panel = whole(page)
    await assertRows(panel, [controls, motion, servo])
    await assertDepth(panel, servo, 2)
    assert.equal(await page.getByRole('tab', { name: 'PM1', exact: true }).count(), 0)

    await write(`/api/v1/components/${servo.id}/move`, { parentComponentId: process.id, reason })
    await write(`/api/v1/components/${servo.id}`, { name: '伺服驱动模块（新归属）', reason }, 'PUT')
    const movedBaseline = await baseline('调整归属基线')
    assert.deepEqual((await get(`/api/v1/baselines/${oldBaseline.id}`)).items, frozen.items, 'Live component edits must not mutate released baseline snapshots')
    await openCompare(page, project.id)
    await selectSide('左侧', '机台', machines[1].id)
    await selectSide('右侧', '基线', oldBaseline.id)
    panel = whole(page)
    await assertDepth(panel, servo, 2)
    assert((await row(panel, servo).innerText()).includes('左：工艺系统 / 伺服驱动模块（新归属）'))
    assert((await row(panel, servo).innerText()).includes('右：控制系统 / 运动控制 / 伺服驱动模块'))
    await selectSide('左侧', '基线', nextBaseline.id)
    await selectSide('右侧', '基线', movedBaseline.id)
    await page.getByRole('checkbox', { name: '只看差异', exact: true }).check()
    panel = whole(page)
    await row(panel, servo).locator('.comparison-tree-path').waitFor()
    await assertRows(panel, [controls, motion, servo])
    await assertDepth(panel, servo, 2)
    const moved = row(panel, servo)
    assert((await moved.getAttribute('class')).includes('hierarchy-changed'))
    assert.equal((await moved.locator('td').nth(0).innerText()).trim(), 'V2.0-control')
    assert.equal((await moved.locator('td').nth(1).innerText()).trim(), 'V2.0-control')
    assert((await moved.innerText()).includes('相同'), 'Unchanged versions remain matched even when their hierarchy changes')
    assert((await moved.innerText()).includes('层级或名称不同'))
    assert((await page.locator('.compare-results-heading').innerText()).includes('0 项版本差异'), 'Version differences must be distinct from hierarchy changes')
    assert((await page.locator('.comparison-structure-summary').innerText()).includes('1 项层级或名称不同'))
    for (const width of [1440, 390]) await screenshot('frozen-baseline-structure-change', width, panel)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: '交换左右配置', exact: true }).click()
    await assertDepth(panel, servo, 1)
    await assertRows(panel, [process, servo])
    assert((await row(panel, servo).innerText()).includes('左：工艺系统 / 伺服驱动模块（新归属）'))
    assert((await row(panel, servo).innerText()).includes('右：控制系统 / 运动控制 / 伺服驱动模块'))

    await write(`/api/v1/projects/${project.id}/standard`, { configurationBaselineId: oldBaseline.id, reason })
    await write(`/api/v1/machines/${machines[1].id}/target`, { configurationBaselineId: oldBaseline.id, reason })
    const openMachine = async (target, section) => {
      await target.goto('/')
      await target.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
      await target.reload()
      await target.locator('.nav-item').filter({ hasText: '机台' }).click()
      await target.locator('.machine-list-item').filter({ hasText: '升级配置实验室机台' }).click()
      await target.getByRole('navigation', { name: '机台详情' }).getByRole('button', { name: section, exact: true }).click()
    }
    await openMachine(page, '目标与对比')
    const targetPanel = page.locator('.machine-target-comparison')
    await targetPanel.locator('summary').click()
    await assertRows(targetPanel, [controls, motion, servo])
    await assertDepth(targetPanel, servo, 2)
    assert((await row(targetPanel, servo).innerText()).includes('基线：控制系统 / 运动控制 / 伺服驱动模块'))
    assert((await row(targetPanel, servo).innerText()).includes('当前目录：工艺系统 / 伺服驱动模块（新归属）'))
    const standardPanel = page.locator('.machine-standard-comparison')
    await assertRows(standardPanel, [controls, motion, servo])
    await targetPanel.getByRole('button', { name: '收起控制系统', exact: true }).click()
    await assertRows(targetPanel, [controls])
    await targetPanel.getByRole('button', { name: '展开控制系统', exact: true }).click()
    for (const width of [1440, 390]) await screenshot('machine-target-hierarchy', width, targetPanel)
    await page.setViewportSize({ width: 1440, height: 1000 })

    // Backdated observations exercise historical grouping without changing known installation times.
    const historyMachine = await write('/api/v1/machines', { projectId: project.id, serialNumber: 'HCT-' + randomUUID().slice(0, 8), name: '层级历史机台', reason })
    const historyEntry = (item, selected) => ({ componentId: item.id, versionId: selected.id, absent: false, knownInstalledAt: null })
    await write(`/api/v1/machines/${historyMachine.id}/facts`, { operationType: 'InitialSnapshot', coverage: 'Full', effectiveAt: '2020-01-01T00:00:00Z', sourceType: 'Manual', reason, items: [historyEntry(servo, servo1), historyEntry(gas, gas1)] })
    await write(`/api/v1/machines/${historyMachine.id}/facts`, { operationType: 'Observation', coverage: 'Partial', effectiveAt: '2021-01-01T00:00:00Z', sourceType: 'Manual', reason, items: [historyEntry(servo, servo2)] })
    const historyBefore = await get(`/api/v1/machines/${historyMachine.id}/configuration-at?at=2020-06-01T00:00:00Z`)
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: '机台' }).click()
    await page.locator('.machine-list-item').filter({ hasText: '层级历史机台' }).click()
    await page.getByRole('navigation', { name: '机台详情' }).getByRole('button', { name: '历史', exact: true }).click()
    const local = new Date('2020-06-01T00:00:00Z')
    await page.getByLabel('查看时间', { exact: true }).fill(new Date(local.getTime() - local.getTimezoneOffset() * 60000).toISOString().slice(0, 16))
    const historyPanel = page.locator('.history-configuration-table')
    await assertRows(historyPanel, [process, servo, gas, controls, sensor])
    await assertDepth(historyPanel, servo, 1)
    assert((await row(historyPanel, sensor).innerText()).includes('已确认缺失'), 'Full snapshot omissions must remain explicit absent facts')
    assert((await row(historyPanel, servo).innerText()).includes('已知安装 未知'))
    assert((await page.locator('.historical-configuration').innerText()).includes('按当前组件目录分组，不代表当时的组件层级'))
    const historyComparison = page.locator('.history-comparison')
    await assertRows(historyComparison, [process, servo])
    assert((await row(historyComparison, servo).innerText()).includes('V1.0-control'))
    assert((await row(historyComparison, servo).innerText()).includes('V2.0-control'))
    for (const width of [1440, 390]) await screenshot('historical-configuration-hierarchy', width, page.locator('.historical-configuration'))
    await page.setViewportSize({ width: 1440, height: 1000 })
    assert.deepEqual(await get(`/api/v1/machines/${historyMachine.id}/configuration-at?at=2020-06-01T00:00:00Z`), historyBefore)

    const openBaselineChanges = async target => {
      await target.locator('.nav-item').filter({ hasText: '基线' }).click()
      await target.locator('.timeline-item').filter({ hasText: '调整归属基线' }).click()
      const changes = target.locator('.baseline-difference')
      await changes.getByText('1 个组件发生变化。', { exact: true }).waitFor()
      await changes.locator('summary').click()
      return changes
    }
    const baselineChanges = await openBaselineChanges(page)
    await assertRows(baselineChanges, [process, servo])
    await assertDepth(baselineChanges, servo, 1)
    assert((await row(baselineChanges, servo).innerText()).includes('旧基线：控制系统 / 运动控制 / 伺服驱动模块'))
    assert((await row(baselineChanges, servo).innerText()).includes('新基线：工艺系统 / 伺服驱动模块（新归属）'))
    assert.equal((await row(baselineChanges, servo).locator('td').nth(0).innerText()).split('\n')[0], 'V2.0-control')
    assert.equal((await row(baselineChanges, servo).locator('td').nth(1).innerText()).split('\n')[0], 'V2.0-control')
    await baselineChanges.getByRole('button', { name: '收起工艺系统', exact: true }).click()
    await assertRows(baselineChanges, [process])
    await baselineChanges.getByRole('button', { name: '展开工艺系统', exact: true }).click()
    for (const width of [1440, 390]) await screenshot('baseline-history-hierarchy', width, baselineChanges)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.locator('.timeline-item').filter({ hasText: '控制升级基线' }).click()
    await page.locator('.baseline-difference h4').getByText('相对于 初始层级基线', { exact: true }).waitFor()
    await page.locator('.baseline-difference summary').click()
    await assertRows(page.locator('.baseline-difference'), [controls, motion, servo])
    await assertDepth(page.locator('.baseline-difference'), servo, 2)

    const userName = 'compare-tree-viewer-' + randomUUID().slice(0, 8)
    const password = randomUUID()
    await write('/api/v1/admin/users', { userName, password, displayName: '只读配置比对验收', role: 'Viewer', reason })
    viewer = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
    await write('/api/v1/auth/login', { userName, password }, 'POST', viewer.request)
    const viewerPage = await viewer.newPage()
    viewerPage.on('pageerror', error => errors.push(error.message))
    await openCompare(viewerPage, project.id)
    await selectSide('左侧', '基线', nextBaseline.id, viewerPage)
    await selectSide('右侧', '基线', movedBaseline.id, viewerPage)
    await viewerPage.getByRole('checkbox', { name: '只看差异', exact: true }).check()
    await assertDepth(whole(viewerPage), servo, 2)
    await assertRows(whole(viewerPage), [controls, motion, servo])
    assert.equal(await viewerPage.locator('.configuration-compare input:not([type="checkbox"]), .configuration-compare textarea').count(), 0)
    assert.equal(await viewerPage.locator('.configuration-compare').getByRole('button', { name: /编辑|保存|删除|维护/ }).count(), 0)
    await openMachine(viewerPage, '目标与对比')
    await viewerPage.locator('.machine-target-comparison summary').click()
    await assertDepth(viewerPage.locator('.machine-target-comparison'), servo, 2)
    const viewerChanges = await openBaselineChanges(viewerPage)
    await assertDepth(viewerChanges, servo, 1)
    assert.equal(await viewerChanges.locator('input, textarea, select').count(), 0)
    assert.deepEqual((await get(`/api/v1/baselines/${oldBaseline.id}`)).items, frozen.items)
    assert.deepEqual(errors, [])
    console.log('Comparison hierarchy acceptance passed: standalone/PM, machine target/standard, historical actual/comparison and baseline-history changes; root order, three levels, collapse, ancestor context, frozen names/parents, hierarchy-only changes, Viewer and 1440/390 layouts.')
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true, animations: 'disabled' }).catch(() => {})
    throw error
  } finally {
    if (project) await write(`/api/v1/projects/${project.id}/archive`, { reason: '配置层级自动验收完成' }).catch(() => {})
    await viewer?.close()
    await browser.close()
  }
}

main().catch(error => { console.error(error.stack); process.exitCode = 1 })
