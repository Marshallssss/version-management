const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const api = context.request
  const call = (url, data, method = 'POST', key = randomUUID(), client = api) => client.fetch(url, { method, data, headers: { 'Idempotency-Key': key } })
  const write = async (url, data, method = 'POST') => { const r = await call(url, data, method); assert(r.ok(), await r.text()); return r.status() === 204 ? null : r.json() }
  const get = async url => { const r = await api.get(url); assert(r.ok(), await r.text()); return r.json() }
  const projects = []; const machines = []
  let page
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const project = await write('/api/v1/projects', { code: 'PM-' + randomUUID().slice(0, 8), name: '腔室配置验收', reason: '自动化验收' }); projects.push(project.id)
    const other = await write('/api/v1/projects', { code: 'PM-OTHER-' + randomUUID().slice(0, 8), name: '其他项目', reason: '自动化验收' }); projects.push(other.id)
    const root = await write(`/api/v1/projects/${project.id}/components`, { name: '下位机', reason: '验收' })
    const a = await write(`/api/v1/projects/${project.id}/components`, { name: '控制程序', parentComponentId: root.id, reason: '验收' })
    const b = await write(`/api/v1/projects/${project.id}/components`, { name: '驱动程序', parentComponentId: root.id, reason: '验收' })
    const foreign = await write(`/api/v1/projects/${other.id}/components`, { name: '外部组件', reason: '验收' })
    const v1 = await write(`/api/v1/components/${a.id}/versions`, { versionNumber: 'V1', maturity: 'Released', reason: '验收' })
    const v2 = await write(`/api/v1/components/${a.id}/versions`, { versionNumber: 'V2-lab', maturity: 'Testing', reason: '验收' })
    const vb = await write(`/api/v1/components/${b.id}/versions`, { versionNumber: 'D1', maturity: 'Released', reason: '验收' })
    const vf = await write(`/api/v1/components/${foreign.id}/versions`, { versionNumber: 'F1', reason: '验收' })
    const baseline = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'PM', baselineCode: 'BL-PM', reason: '验收' })
    for (const action of ['review', 'review/approve', 'release']) await write(`/api/v1/baselines/${baseline.id}/${action}`, { reason: '验收' })
    const machine = await write('/api/v1/machines', { projectId: project.id, serialNumber: 'PM-' + randomUUID().slice(0, 8), name: '一号工艺机', location: 'A 区', owner: '张工', stage: 'MoveIn', chambers: [{ number: 1, stage: 'T0' }, { number: 6, stage: 'Lab' }], reason: '验收' }); machines.push(machine.id)
    for (const [name, location] of [['三号工艺机', 'B 区'], ['二号工艺机', 'A 区']]) {
      const m = await write('/api/v1/machines', { projectId: project.id, serialNumber: 'M-' + randomUUID().slice(0, 8), name, location, stage: 'Lab', reason: '验收' }); machines.push(m.id)
    }
    const equipmentUrl = `/api/v1/machines/${machine.id}/equipment`
    const overridesUrl = `/api/v1/machines/${machine.id}/chambers/6/configuration`
    let data = await get(equipmentUrl)
    assert.equal(data.owner, '张工'); assert.equal(data.stage, 'MoveIn')
    assert.deepEqual(data.chambers.map(x => x.number), [1, 6]); assert.equal(data.history.length, 3)
    await write(`/api/v1/machines/${machine.id}/facts`, { operationType: 'InitialSnapshot', coverage: 'Full', sourceType: 'Manual', reason: '整机配置', items: [{ componentId: a.id, versionId: v1.id, absent: false, knownInstalledAt: null }, { componentId: b.id, versionId: vb.id, absent: false, knownInstalledAt: null }] })
    const wholeBefore = await get(`/api/v1/machines/${machine.id}/configuration`)
    const update = { owner: '李工', stage: 'T1', chambers: [{ number: 1, stage: 'T1' }, { number: 2, stage: 'Lab' }, { number: 5, stage: 'Lab' }, { number: 6, stage: 'T0' }], reason: '扩展腔室与阶段' }
    const key = randomUUID()
    for (const r of await Promise.all([call(equipmentUrl, update, 'PUT', key), call(equipmentUrl, update, 'PUT', key)])) assert.equal(r.status(), 200, await r.text())
    const historyCount = (await get(equipmentUrl)).history.length
    assert.equal((await call(equipmentUrl, { ...update, stage: 'T2' }, 'PUT', key)).status(), 409)
    assert.equal((await get(equipmentUrl)).history.length, historyCount)
    for (const invalid of [{ ...update, stage: 'Invalid' }, { ...update, chambers: [{ number: 7, stage: 'Lab' }] }, { ...update, chambers: [{ number: 1, stage: 'Lab' }, { number: 1, stage: 'T1' }] }, { ...update, reason: '' }]) assert.equal((await call(equipmentUrl, invalid, 'PUT')).status(), 400)
    for (const item of [{ componentId: a.id, versionId: vb.id }, { componentId: foreign.id, versionId: vf.id }]) assert.equal((await call(overridesUrl, { items: [item], reason: '非法' }, 'PUT')).status(), 400)
    assert.equal((await call(`/api/v1/machines/${machine.id}/chambers/3/configuration`, { items: [], reason: '未安装' }, 'PUT')).status(), 400)
    await write(overridesUrl, { items: [{ componentId: a.id, versionId: v2.id }], reason: 'PM6 测试特例' }, 'PUT')
    data = await get(equipmentUrl)
    assert.equal(data.chambers.find(x => x.number === 6).overrides[0].match, 'Unknown')
    await write(`/api/v1/machines/${machine.id}/target`, { configurationBaselineId: baseline.id, reason: '显式目标' })
    assert.equal((await get(equipmentUrl)).chambers.find(x => x.number === 6).overrides[0].match, 'Mismatch')
    await write(overridesUrl, { items: [{ componentId: a.id, versionId: v1.id }], reason: '匹配验收' }, 'PUT')
    await write(`/api/v1/component-versions/${v1.id}/safety`, { state: 'Blocked', reason: '风险独立验收' })
    const special = (await get(equipmentUrl)).chambers.find(x => x.number === 6).overrides[0]
    assert.equal(special.match, 'Matched'); assert.equal(special.risk, 'Critical')
    assert.deepEqual(await get(`/api/v1/machines/${machine.id}/configuration`), wholeBefore)
    assert.equal((await call(`/api/v1/component-versions/${v2.id}`, { reason: '保护特例历史' }, 'DELETE')).status(), 409)
    for (const role of ['Viewer', 'Engineer']) {
      const userName = role + randomUUID().slice(0, 8); const password = randomUUID()
      await write('/api/v1/admin/users', { userName, displayName: '权限验收', password, role, reason: '验收' })
      const otherContext = await browser.newContext({ baseURL })
      await call('/api/v1/auth/login', { userName, password }, 'POST', randomUUID(), otherContext.request)
      assert.equal((await call(`/api/v1/machines/${machine.id}`, { reason: '越权删除' }, 'DELETE', randomUUID(), otherContext.request)).status(), 403)
      assert.equal((await call(equipmentUrl, update, 'PUT', randomUUID(), otherContext.request)).status(), 403)
      assert.equal((await call(overridesUrl, { items: [], reason: '越权修改' }, 'PUT', randomUUID(), otherContext.request)).status(), 403)
      await otherContext.close()
    }
    page = await context.newPage(); const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/'); await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id); await page.reload()
    await page.locator('.nav-item').filter({ hasText: '机台' }).click()
    await page.getByRole('button', { name: /一号工艺机/ }).waitFor()
    assert.equal(await page.locator('.machine-detail-panel:visible').count(), 0)
    assert.deepEqual(await page.locator('.machine-location-group h4').allTextContents(), ['A 区', 'B 区'])
    mkdirSync('artifacts/machine-equipment', { recursive: true })
    await page.screenshot({ path: 'artifacts/machine-equipment/list-desktop.png', fullPage: true })
    await page.getByRole('button', { name: /一号工艺机/ }).click()
    await page.getByRole('button', { name: '编辑阶段与腔室' }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('整机阶段').selectOption('T2')
    await dialog.getByLabel('PM5 阶段').selectOption('STR')
    await dialog.getByLabel('变更原因').fill('界面阶段更新')
    await dialog.getByRole('button', { name: '保存配置' }).click(); await dialog.waitFor({ state: 'hidden' })
    assert.equal((await get(equipmentUrl)).stage, 'T2')
    await page.getByRole('button', { name: '新建机台 / 从已有机台复制资料' }).click()
    const creation = page.locator('.machine-create')
    await creation.getByLabel('复制已有机台').selectOption(machine.id)
    await page.waitForFunction(() => document.querySelector('.machine-create select[aria-label="PM5 阶段"]')?.value === 'STR')
    await creation.getByLabel('机台序列号').fill('UI-' + randomUUID().slice(0, 8))
    await creation.getByLabel('机台名称').fill('复制机台')
    await creation.getByLabel('机台负责人').fill('王工')
    await creation.getByLabel('创建原因').fill('界面复制验收')
    const created = page.waitForResponse(r => r.url().endsWith('/api/v1/machines') && r.request().method() === 'POST')
    await creation.getByRole('button', { name: '创建机台', exact: true }).click()
    const copy = await (await created).json(); machines.push(copy.id)
    const copied = await get(`/api/v1/machines/${copy.id}/equipment`)
    assert.equal(copied.owner, '王工'); assert.equal(copied.stage, 'T2')
    assert.equal(copied.chambers.find(c => c.number === 5).stage, 'STR')
    assert(copied.chambers.every(c => c.overrides.length === 0))
    await page.getByRole('button', { name: /一号工艺机/ }).click()
    await page.locator('.chamber-summary article').filter({ hasText: 'PM6' }).getByRole('button', { name: /特例/ }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: /移除 .* 特例/ }).click()
    await dialog.getByLabel('特例组件').selectOption(b.id); await dialog.getByLabel('特例版本').selectOption(vb.id)
    await dialog.getByRole('button', { name: '加入特例' }).click()
    await dialog.getByLabel('变更原因').fill('独立录入驱动特例')
    await page.evaluate(async () => { await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); await Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))) })
    await page.screenshot({ path: 'artifacts/machine-equipment/override-desktop.png' })
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.evaluate(async () => { await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); await Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))) })
    const bounds = await dialog.boundingBox(); assert(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 391)
    await page.screenshot({ path: 'artifacts/machine-equipment/override-mobile.png' })
    await dialog.getByRole('button', { name: '保存配置' }).click(); await dialog.waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.locator('.equipment-actions').getByRole('button', { name: '设备历史', exact: true }).click()
    await page.getByRole('dialog').getByLabel('记录范围').selectOption('5')
    assert((await page.locator('.equipment-history').innerText()).includes('STR'))
    await page.screenshot({ path: 'artifacts/machine-equipment/history.png' }); await page.locator('.ant-modal-close').click()
    await page.locator('.nav-item').filter({ hasText: '项目' }).click(); await page.locator('.nav-item').filter({ hasText: '机台' }).click()
    assert.equal(await page.locator('.machine-detail-panel:visible').count(), 0)
    await page.getByRole('button', { name: /一号工艺机/ }).click()
    await page.getByRole('button', { name: '删除机台', exact: true }).click()
    assert(await page.getByRole('button', { name: '确认删除机台' }).isDisabled())
    await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
    assert((await get('/api/v1/machines')).some(x => x.id === machine.id))
    await write(equipmentUrl, { ...update, chambers: update.chambers.filter(x => x.number !== 6), reason: '移除 PM6' }, 'PUT')
    assert(!(await get(equipmentUrl)).chambers.find(x => x.number === 6).installed)
    await write(equipmentUrl, { ...update, reason: '重新加入 PM6' }, 'PUT')
    assert.equal((await get(equipmentUrl)).chambers.find(x => x.number === 6).overrides.length, 0)
    await page.getByRole('button', { name: '删除机台', exact: true }).click()
    await page.getByRole('dialog').getByLabel('删除原因').fill('删除验收机台')
    await page.getByRole('button', { name: '确认删除机台' }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert(!(await get('/api/v1/machines')).some(x => x.id === machine.id))
    assert.equal((await api.get(equipmentUrl)).status(), 404)
    const audits = await get(`/api/v1/audit?entityId=${machine.id}`)
    assert(audits.some(x => x.action === 'MachineDeleted'))
    assert(audits.every(x => x.actor && x.correlationId))
    assert.deepEqual(errors, [])
    console.log('Machine equipment acceptance passed: PM combinations, stages/owner/history, isolated overrides, target match/risk, permissions, idempotency, delete and responsive UI.')
  } catch (error) {
    if (page) { mkdirSync('artifacts/machine-equipment', { recursive: true }); await page.screenshot({ path: 'artifacts/machine-equipment/failure.png', fullPage: true }) }
    throw error
  } finally {
    for (const id of machines) await call(`/api/v1/machines/${id}`, { reason: '验收清理' }, 'DELETE').catch(() => {})
    for (const id of projects) await call(`/api/v1/projects/${id}/archive`, { reason: '验收清理' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
