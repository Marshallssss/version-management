const { chromium } = require('playwright')
const { readFileSync, writeFileSync, mkdirSync, copyFileSync } = require('node:fs')
const { execFileSync } = require('node:child_process')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL })
  const api = context.request
  const token = randomUUID().slice(0, 8)
  const output = path.resolve('artifacts/matrix-import', token)
  mkdirSync(output, { recursive: true })
  const workbook = path.join(output, 'project.xlsx')
  const fixture = (changes = {}, file = workbook, legacyLayout = false) => JSON.parse(execFileSync('powershell.exe', [
    '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', path.resolve('tests/integration/matrix-workbook-fixture.ps1'),
    '-Path', file, '-CellsJson', JSON.stringify(changes),
    ...(legacyLayout ? ['-LegacyLayout'] : []),
  ], { encoding: 'utf8', windowsHide: true }).replace(/^\uFEFF/, ''))
  const write = async (url, data, method = 'POST', key = randomUUID()) => {
    const response = await api.fetch(url, { method, data, headers: { 'Idempotency-Key': key } })
    assert(response.ok(), `${url}: ${await response.text()}`)
    return response.status() === 204 ? null : response.json()
  }
  const get = async url => { const response = await api.get(url); assert(response.ok(), await response.text()); return response.json() }
  let project
  let route
  let template
  let source
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    project = await write('/api/v1/projects', { code: `MATRIX ${token}`, name: `矩阵导入验收 ${token}`, reason: '自动验收' })
    route = `/api/v1/projects/${project.id}/matrix-import`
    const group = await write(`/api/v1/projects/${project.id}/components`, { name: '控制系统分类', reason: '验收' })
    const a = await write(`/api/v1/projects/${project.id}/components`, { name: '主控', parentComponentId: group.id, reason: '验收' })
    const b = await write(`/api/v1/projects/${project.id}/components`, { name: '驱动', parentComponentId: group.id, reason: '验收' })
    const ui = await write(`/api/v1/projects/${project.id}/components`, { name: '操作界面', reason: '验收' })
    const v0 = {}
    for (const component of [a, b, ui]) v0[component.id] = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V1.0', maturity: 'Released', reason: '初始标准' })
    const baseline = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'MATRIX', baselineCode: 'MATRIX-1', publishImmediately: true, reason: '初始标准' })
    await write(`/api/v1/projects/${project.id}/standard`, { configurationBaselineId: baseline.id, reason: '初始标准' })
    template = await write(`${route}/templates`, { reason: '矩阵验收模板' })
    const download = await api.get(template.downloadUrl)
    assert(download.ok(), await download.text())
    assert.match(download.headers()['content-type'], /spreadsheetml/)
    writeFileSync(workbook, await download.body())
    const cells = fixture({}, workbook, true)
    const column = component => Object.entries(cells).find(([cell, value]) => cell.endsWith('1') && value === component.id)?.[0].replace(/1$/, '')
    const aCol = column(a), bCol = column(b), uiCol = column(ui)
    assert(aCol && bCol && uiCol, 'Every version component has a bound template column')
    assert.equal(column(group), undefined, 'Classification node is a header, not a version input')
    assert.match(cells[`${aCol}4`], /主控/)
    assert.equal(cells[`${uiCol}5`], 'V1.0')
    const scan = async (file = workbook) => write(`${route}/scan`, { templateId: template.id, fileName: path.basename(file), contentBase64: readFileSync(file).toString('base64'), reason: '矩阵扫描验收' })
    const state = () => get(route)
    const detail = () => get(`/api/v1/projects/${project.id}`)
    const newUi = await write(`/api/v1/components/${ui.id}/versions`, { versionNumber: 'V9.0', maturity: 'Released', reason: '模板生成后标准变化' })
    const baseline2 = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'MATRIX', baselineCode: 'MATRIX-2', publishImmediately: true, reason: '新标准' })
    await write(`/api/v1/projects/${project.id}/standard`, { configurationBaselineId: baseline2.id, reason: '新标准' })
    await scan()
    assert.equal((await state()).combinations.length, 0, 'Blank rows do not create combinations')
    fixture({ B6: '2026-09-16', C6: '修复主控通信', D6: '可导入', [`${aCol}6`]: '001.02', B7: '2026-09-17', C7: '驱动联调', D7: '可导入', [`${bCol}7`]: 'V2.1' })
    await scan()
    let imported = (await state()).combinations.sort((x, y) => x.sequenceNo - y.sequenceNo)
    assert.equal(imported.length, 2)
    const item = (combo, component) => combo.items.find(value => value.componentId === component.id)
    assert.equal(item(imported[0], a).versionNumber, '001.02')
    assert.equal(item(imported[0], b).versionId, v0[b.id].id)
    assert.equal(item(imported[1], a).versionNumber, '001.02')
    assert.equal(item(imported[1], b).versionNumber, 'V2.1')
    assert.equal(item(imported[1], ui).versionId, v0[ui.id].id, 'Blank inheritance stays on the frozen reference, not new standard')
    assert.notEqual(item(imported[1], ui).versionId, newUi.id)
    let catalog = await detail()
    let first = catalog.components.find(value => value.id === a.id).versions.find(value => value.versionNumber === '001.02')
    assert.equal(first.maturity, 'Testing')
    const frozen = JSON.stringify(imported.map(value => value.items))
    await scan()
    assert.equal((await state()).combinations.length, 2, 'Same bytes do not reimport')
    fixture({ B8: '2026-09-17', C8: '第二次主控修正', D8: '可导入', [`${aCol}8`]: '001.03' })
    await scan()
    catalog = await detail()
    const aVersions = catalog.components.find(value => value.id === a.id).versions
    const latest = aVersions.find(value => value.versionNumber === '001.03')
    assert.equal(aVersions.find(value => value.id === first.id).maturity, 'Deprecated')
    assert.equal(latest.maturity, 'Testing')
    assert(latest.sequenceNo > first.sequenceNo)
    imported = (await state()).combinations.sort((x, y) => x.sequenceNo - y.sequenceNo)
    assert.equal(JSON.stringify(imported.slice(0, 2).map(value => value.items)), frozen)
    await write(`/api/v1/component-versions/${latest.id}/maturity`, { state: 'Released', reason: '发布后重扫保护' })
    await scan()
    assert.equal((await detail()).components.find(value => value.id === a.id).versions.find(value => value.id === latest.id).maturity, 'Released')
    const invalid = path.join(output, 'invalid.xlsx')
    copyFileSync(workbook, invalid)
    fixture({ C6: '篡改已导入说明', [`${aCol}6`]: 'DO-NOT-CREATE' }, invalid)
    await scan(invalid)
    assert.equal((await state()).combinations.length, 3)
    assert(!(await detail()).components.some(value => value.versions.some(version => version.versionNumber === 'DO-NOT-CREATE')))
    copyFileSync(workbook, invalid)
    fixture({ B9: '2026-09-17', C9: '必须整体回滚', D9: '可导入', [`${aCol}9`]: 'ROLLBACK', [`${bCol}9`]: 'x'.repeat(161) }, invalid)
    await scan(invalid)
    assert(!(await detail()).components.some(value => value.versions.some(version => version.versionNumber === 'ROLLBACK')))
    copyFileSync(workbook, invalid)
    fixture({ B9: '2026-09-17', C9: '前一新行也必须回滚', D9: '可导入', [`${aCol}9`]: 'ROLLBACK', [`${bCol}9`]: 'ROLLBACK-DRIVER', B10: 'invalid-date', C10: '后一行日期无效', D10: '可导入', [`${bCol}10`]: 'INVALID-ROW' }, invalid)
    const rolledBack = await scan(invalid)
    assert.equal(rolledBack.status, 'Failed')
    assert.equal(rolledBack.importedCount, 0)
    catalog = await detail()
    assert(!catalog.components.some(value => value.versions.some(version => ['ROLLBACK', 'ROLLBACK-DRIVER', 'INVALID-ROW'].includes(version.versionNumber))))
    assert.equal(catalog.components.find(value => value.id === b.id).versions.find(version => version.versionNumber === 'V2.1').maturity, 'Testing', 'Rollback must restore prior Testing maturity after an earlier row was saved')
    copyFileSync(workbook, invalid)
    fixture({ B9: '2026-09-17', C9: '未确认的前序记录', D9: '待填写', [`${aCol}9`]: 'WAITING', B10: '2026-09-18', C10: '不能跳过前序记录', D10: '可导入', [`${bCol}10`]: 'NO-SKIP' }, invalid)
    assert.equal((await scan(invalid)).status, 'Failed')
    assert.equal((await state()).combinations.length, 3)
    copyFileSync(workbook, invalid)
    fixture({ B9: '2026-09-17', C9: '公式不能作为版本', D9: '可导入', [`${aCol}9`]: { formula: '1+1' } }, invalid)
    await scan(invalid)
    assert.equal((await state()).combinations.length, 3)
    copyFileSync(workbook, invalid)
    fixture({ Z6: '不属于组件模板的值' }, invalid)
    assert.equal((await scan(invalid)).status, 'Failed', 'Unbound columns cannot be silently ignored')
    copyFileSync(workbook, invalid)
    fixture({ A7: cells.A6 }, invalid)
    await scan(invalid)
    assert.equal((await state()).combinations.length, 3)
    const impact = await get(`/api/v1/component-versions/${first.id}/operation-impact`)
    assert.equal(impact.canDelete, true, 'An administrator can correct an imported version while preserving combination snapshots')
    assert(impact.groups.find(group => group.kind === 'matrix-combinations')?.total > 0)
    const referenceImpact = await get(`/api/v1/component-versions/${v0[ui.id].id}/operation-impact`)
    assert(referenceImpact.groups.find(group => group.kind === 'matrix-templates')?.total > 0)
    source = { templateId: template.id, path: workbook, localTime: '23:59', timeZoneId: 'Asia/Shanghai', enabled: false, reason: '本地固定源验收' }
    await write(`${route}/source`, source, 'PUT')
    await write(`${route}/source/scan`, { reason: '立即扫描固定源' })
    assert.equal((await state()).combinations.length, 3)
    if (process.env.CONFIGHUB_TEST_SCHEDULE === '1') {
      fixture({ B9: '2026-09-17', C9: '后台定时扫描验收', D9: '可导入', [`${bCol}9`]: 'SCHEDULE.1' })
      const due = new Date(Date.now() + 60000)
      source = { ...source, enabled: true, timeZoneId: 'UTC', localTime: due.toISOString().slice(11, 16), reason: '真实每日调度验收' }
      await write(`${route}/source`, source, 'PUT')
      let scheduled = false
      for (let i = 0; i < 90; i++) {
        const current = await state()
        if (current.combinations.length === 4) { assert(current.runs.some(run => run.actor.startsWith('自动扫描:') && run.importedCount === 1)); scheduled = true; break }
        await new Promise(resolve => setTimeout(resolve, 1000))
      }
      assert(scheduled, 'The running Worker must execute the daily source without a browser trigger')
      await write(`${route}/source`, { ...source, enabled: false, reason: '调度验收完成' }, 'PUT')
    }
    const anonymous = await browser.newContext({ baseURL })
    assert.equal((await anonymous.request.get(route)).status(), 401)
    assert.equal((await anonymous.request.get(template.downloadUrl)).status(), 401)
    await anonymous.close()
    for (const role of ['Viewer', 'Engineer', 'SeniorEngineer']) {
      const userName = `matrix-${role}-${token}`
      const password = randomUUID()
      const user = await write('/api/v1/admin/users', { userName, displayName: `${role} 导入验收`, password, role, reason: '权限验收' })
      const member = await browser.newContext({ baseURL })
      try {
        assert((await member.request.post('/api/v1/auth/login', { data: { userName, password } })).ok())
        const payload = { templateId: template.id, fileName: 'permissions.xlsx', contentBase64: readFileSync(workbook).toString('base64'), reason: '权限与重放验收' }
        const key = randomUUID()
        const memberScan = () => member.request.post(`${route}/scan`, { data: payload, headers: { 'Idempotency-Key': key } })
        assert.equal((await memberScan()).status(), 403, 'Role alone cannot import without project membership')
        if (role !== 'SeniorEngineer') continue
        await write(`/api/v1/projects/${project.id}/members`, { userId: user.id, role: 'SeniorEngineer', reason: '项目范围授权' })
        assert((await memberScan()).ok(), 'A project senior engineer can import')
        const configure = await member.request.put(`${route}/source`, { data: source, headers: { 'Idempotency-Key': randomUUID() } })
        assert.equal(configure.status(), 403, 'Server file access is administrator-only')
        await write(`/api/v1/projects/${project.id}/members`, { userId: user.id, role: 'Engineer', reason: '撤销项目高级权限' })
        assert.equal((await memberScan()).status(), 403, 'Revoked membership must reject successful idempotent replay')
      } finally { await member.close() }
    }
    const page = await context.newPage()
    const pageErrors = []
    page.on('pageerror', error => pageErrors.push(error.message))
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: /^版本导入$/ }).click()
    await page.locator('.matrix-import-workspace').getByRole('heading', { name: '版本导入', exact: true }).waitFor()
    await page.getByLabel('测试组合详情', { exact: true }).waitFor()
    assert(await page.getByLabel('测试组合详情', { exact: true }).getByText('控制系统分类', { exact: true }).isVisible())
    await page.getByLabel('填写后的 Excel 文件').setInputFiles(workbook)
    await page.getByLabel('本次录入原因').fill('界面重复扫描验收')
    await page.getByRole('button', { name: '扫描并录入', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '扫描完成：新增 0 套' }).waitFor()
    await page.getByRole('button', { name: /^测试组合/ }).click()
    await page.screenshot({ path: 'artifacts/matrix-import/desktop.png', fullPage: true })
    await page.getByRole('button', { name: '扫描设置', exact: true }).click()
    await page.getByLabel('部署电脑上的 Excel 路径').waitFor()
    assert.equal(await page.getByLabel('部署电脑上的 Excel 路径').inputValue(), workbook)
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile matrix workspace must not overflow')
    await page.screenshot({ path: 'artifacts/matrix-import/mobile.png', fullPage: true })
    assert.deepEqual(pageErrors, [])
    const other = await write('/api/v1/projects', { code: `MATRIX-OTHER-${token}`, name: '跨项目验证', reason: '验收' })
    try {
      const wrongProject = await api.post(`/api/v1/projects/${other.id}/matrix-import/scan`, { data: { templateId: template.id, fileName: 'wrong.xlsx', contentBase64: readFileSync(workbook).toString('base64'), reason: '跨项目拒绝' }, headers: { 'Idempotency-Key': randomUUID() } })
      assert([400, 403, 404, 409].includes(wrongProject.status()), await wrongProject.text())
    } finally { await write(`/api/v1/projects/${other.id}/archive`, { reason: '验收结束' }) }
    console.log('Matrix import acceptance passed: real XLSX, component bindings, frozen inheritance, Testing-only, supersession, replay, atomic validation, formula/identity rejection, source scan and project protection.')
  } finally {
    if (source && route) await write(`${route}/source`, { ...source, enabled: false, reason: '验收结束' }, 'PUT').catch(() => {})
    if (project) await write(`/api/v1/projects/${project.id}/archive`, { reason: '矩阵自动验收结束' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
