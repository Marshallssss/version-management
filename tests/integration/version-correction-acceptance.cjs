const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')
const { execFileSync } = require('node:child_process')
async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL: process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080', viewport: { width: 1440, height: 900 } })
  const api = context.request, reason = '版本纠错自动验收'
  const call = (url, data, method = 'POST', key = randomUUID(), client = api) => client.fetch(url, { method, data, headers: { 'Idempotency-Key': key } })
  const write = async (url, data, method = 'POST', key) => { const r = await call(url, data, method, key); assert(r.ok(), `${url}: ${await r.text()}`); return r.status() === 204 ? null : r.json() }
  const get = async url => { const r = await api.get(url); assert(r.ok(), await r.text()); return r.json() }
  let project, machine
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    project = await write('/api/v1/projects', { code: `CORRECT-${randomUUID().slice(0, 8)}`, name: '版本纠错验收项目', reason })
    const component = await write(`/api/v1/projects/${project.id}/components`, { name: '控制软件', reason })
    const url = `/api/v1/components/${component.id}/versions`
    const testing = await write(url, { versionNumber: '当前测试', maturity: 'Testing', reason })
    const input = { versionNumber: '历史版本', historicalCreatedAt: '2020-03-04T05:06:00Z', reason }, key = randomUUID()
    const historical = await write(url, input, 'POST', key)
    assert.equal((await write(url, input, 'POST', key)).id, historical.id)
    let detail = await get(`/api/v1/component-versions/${historical.id}`)
    assert.equal(new Date(detail.version.createdAt).toISOString(), '2020-03-04T05:06:00.000Z')
    assert.equal(detail.version.maturity, 'Released')
    assert.equal((await get(`/api/v1/component-versions/${testing.id}`)).version.maturity, 'Testing')
    const audits = await get(`/api/v1/audit?entityId=${historical.id}`)
    assert(audits.some(x => x.action === 'HistoricalComponentVersionRegistered' && new Date(x.occurredAt) > new Date('2026-01-01')))
    assert.equal((await call(url, { ...input, historicalCreatedAt: '2099-01-01T00:00:00Z' })).status(), 400)
    assert.equal((await call(url, input)).status(), 409)
    machine = await write('/api/v1/machines', { projectId: project.id, serialNumber: randomUUID(), name: '负责人验收机台', stage: 'Lab', owner: '原负责人', chambers: [{ number: 1, stage: 'Lab' }], reason })
    const machineUrl = `/api/v1/machines/${machine.id}`
    const machineInfo = (await get('/api/v1/machines')).find(x => x.id === machine.id)
    const update = { serialNumber: machineInfo.serialNumber, name: machineInfo.name, status: 'Active', owner: '新负责人', reason }
    await write(machineUrl, update, 'PUT')
    let equipment = await get(`${machineUrl}/equipment`)
    assert.equal(equipment.owner, '新负责人')
    await write(machineUrl, { ...update, owner: undefined }, 'PUT')
    assert.equal((await get(`${machineUrl}/equipment`)).owner, '新负责人')
    assert.equal((await call(machineUrl, { ...update, owner: 'x'.repeat(161) }, 'PUT')).status(), 400)
    const facts = versionId => ({ operationType: 'Observation', coverage: 'Partial', sourceType: 'Manual', effectiveAt: new Date().toISOString(), reason, items: [{ componentId: component.id, versionId }] })
    await write(`${machineUrl}/facts`, facts(historical.id))
    const historicalPoint = (await get(`${machineUrl}/facts`))[0].effectiveAt
    assert.equal((await call(`/api/v1/component-versions/${historical.id}`, { reason }, 'DELETE')).status(), 409)
    await write(`${machineUrl}/facts`, facts(testing.id))
    const deletionKey = randomUUID()
    assert.equal((await get(`/api/v1/component-versions/${historical.id}/operation-impact`)).canDelete, true)
    await write(`/api/v1/component-versions/${historical.id}`, { reason }, 'DELETE', deletionKey)
    await write(`/api/v1/component-versions/${historical.id}`, { reason }, 'DELETE', deletionKey)
    assert(!(await get(`/api/v1/projects/${project.id}`)).components[0].versions.some(x => x.id === historical.id))
    assert.equal((await get(`/api/v1/component-versions/${historical.id}`)).version.versionNumber, '历史版本')
    assert(JSON.stringify(await get(`${machineUrl}/configuration-at?at=${encodeURIComponent(historicalPoint)}`)).includes('历史版本'), 'Machine history retains version name')
    assert.equal((await call(`${machineUrl}/facts`, facts(historical.id))).status(), 400)
    assert.equal((await call(url, input)).status(), 409)
    const baselineVersion = await write(url, { versionNumber: '受保护基线版本', historicalCreatedAt: input.historicalCreatedAt, reason })
    execFileSync('pwsh', ['-NoProfile', '-File', 'tests/integration/retained-version-database-acceptance.ps1', '-DeletedVersionId', historical.id, '-CurrentVersionId', testing.id, '-MachineId', machine.id], { stdio: 'pipe' })
    const pmVersion = await write(url, { versionNumber: '腔室特例', maturity: 'Draft', reason })
    await write(`${machineUrl}/chambers/1/configuration`, { items: [{ componentId: component.id, versionId: pmVersion.id }], reason }, 'PUT')
    assert.equal((await get(`/api/v1/component-versions/${pmVersion.id}/operation-impact`)).canDelete, false)
    assert.equal((await call(`/api/v1/component-versions/${pmVersion.id}`, { reason }, 'DELETE')).status(), 409)
    await write(`${machineUrl}/chambers/1/configuration`, { items: [], reason }, 'PUT')
    await write(`/api/v1/component-versions/${pmVersion.id}`, { reason }, 'DELETE')
    assert((await get(`/api/v1/component-versions/${pmVersion.id}/impact`)).chamberImpact, 'Retained PM history remains readable')
    await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'PROTECT', baselineCode: '保护基线', reason })
    assert.equal((await call(`/api/v1/component-versions/${baselineVersion.id}`, { reason }, 'DELETE')).status(), 409)
    const userName = `viewer-${randomUUID().slice(0,8)}`, password = randomUUID()
    await write('/api/v1/admin/users', { userName, password, displayName: '只读验收', role: 'Viewer', reason })
    const viewer = await browser.newContext({ baseURL: context._options.baseURL })
    await viewer.request.post('/api/v1/auth/login', { data: { userName, password } })
    assert.equal((await call(url, input, 'POST', key, viewer.request)).status(), 403)
    assert.equal((await call(`/api/v1/component-versions/${testing.id}`, { reason }, 'DELETE', randomUUID(), viewer.request)).status(), 403)
    assert.equal((await call(machineUrl, update, 'PUT', randomUUID(), viewer.request)).status(), 403)
    const page = await context.newPage()
    await page.goto('/'); await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id); await page.reload()
    await page.locator('.nav-item').filter({ hasText: /^机台$/ }).click()
    await page.getByRole('button', { name: /负责人验收机台/ }).click()
    for (const name of ['当前配置', '目标与对比', '阶段与腔室', '历史']) {
      const tab = page.getByRole('navigation', { name: '机台详情' }).getByRole('button', { name, exact: true })
      if (await tab.count()) await tab.click()
      await page.getByRole('button', { name: '返回机台列表', exact: true }).waitFor()
    }
    await page.getByRole('button', { name: '编辑机台资料' }).click()
    await page.getByLabel('机台负责人', { exact: true }).fill('页面负责人')
    await page.getByLabel('修改原因', { exact: true }).fill(reason)
    await page.getByRole('button', { name: '保存资料', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.equal((await get(`${machineUrl}/equipment`)).owner, '页面负责人')
    mkdirSync('artifacts/version-correction', { recursive: true })
    await page.screenshot({ path: 'artifacts/version-correction/machine.png', fullPage: true })
    await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
    assert(await page.locator('.machine-return-bar').evaluate(node => { const r = node.getBoundingClientRect(); return r.top >= 0 && r.bottom <= innerHeight }), 'Return entry remains visible while scrolling')
    await page.getByRole('button', { name: '返回机台列表', exact: true }).click()
    assert.equal(await page.locator('.machine-detail-panel:visible').count(), 0)
    await page.locator('.nav-item').filter({ hasText: /^版本$/ }).click()
    await page.locator('.root-node').first().click()
    await page.getByRole('button', { name: '登记新版本', exact: true }).click()
    await page.getByLabel('补录历史已发布版本').check()
    await page.getByLabel('历史登记时间（本地时间）', { exact: true }).fill('2021-06-07T08:09')
    await page.locator('.inspector-form:visible').getByLabel('版本号', { exact: true }).fill('页面历史版本')
    await page.locator('.inspector-form:visible').getByLabel('登记原因', { exact: true }).fill(reason)
    await page.screenshot({ path: 'artifacts/version-correction/historical-entry.png', fullPage: true })
    await page.getByRole('button', { name: '补录历史版本', exact: true }).click()
    await page.getByRole('button', { name: '补录历史版本', exact: true }).waitFor({ state: 'hidden' })
    assert((await get(`/api/v1/projects/${project.id}`)).components[0].versions.some(x => x.versionNumber === '页面历史版本' && x.maturity === 'Released'))
    console.log('Version correction acceptance passed: historical timestamp/audit, admin RBAC, protected references, retained history, replay, owner API/UI and shared return entry.')
  } finally {
    if (machine) await call(`/api/v1/machines/${machine.id}`, { reason }, 'DELETE')
    if (project) await call(`/api/v1/projects/${project.id}/archive`, { reason })
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
