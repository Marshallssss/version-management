const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const api = context.request
  const projects = []
  const write = async (url, data, method = 'POST') => {
    const response = await api.fetch(url, { method, data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), `${url}: ${await response.text()}`)
    return response.status() === 204 ? null : response.json()
  }
  const get = async url => { const response = await api.get(url); assert(response.ok(), await response.text()); return response.json() }
  const token = randomUUID().slice(0, 8)
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const project = await write('/api/v1/projects', { code: `REGISTRY-${token}`, name: `机台筛选验收 ${token}`, reason: '自动验收' })
    const foreign = await write('/api/v1/projects', { code: `REGISTRY-OTHER-${token}`, name: `外部机台 ${token}`, reason: '自动验收' })
    projects.push(project.id, foreign.id)
    const component = await write(`/api/v1/projects/${project.id}/components`, { name: '控制软件', reason: '验收' })
    const driver = await write(`/api/v1/projects/${project.id}/components`, { name: '驱动软件', reason: '验收' })
    const v1 = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'REG.1', maturity: 'Released', reason: '验收' })
    const d1 = await write(`/api/v1/components/${driver.id}/versions`, { versionNumber: 'DRV.1', maturity: 'Released', reason: '验收' })
    const baseline = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'REGISTRY', baselineCode: 'REGISTRY-BASELINE', publishImmediately: true, reason: '验收' })
    const v2 = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'REG.2-TEST', maturity: 'Testing', reason: '验收' })
    const machineInput = (name, location, stage, owner, projectId = project.id) => ({ projectId, serialNumber: `${name}-${token}`, name, location, stage, owner, chambers: [{ number: 1, stage }, { number: 6, stage: 'Lab' }], reason: '验收' })
    const firstInput = machineInput('A 一号机', '上海', 'T1', '张工')
    const secondInput = machineInput('B 二号机', '上海', 'HVM', '李工')
    const a = await write('/api/v1/machines', firstInput)
    const b = await write('/api/v1/machines', secondInput)
    const c = await write('/api/v1/machines', machineInput('C 三号机', '深圳', 'Lab', '王工'))
    await write('/api/v1/machines', machineInput('外部不可见机台', '北京', 'Lab', '外部负责人', foreign.id))
    for (const [machine, version] of [[a, v1], [b, v2]]) {
      await write(`/api/v1/machines/${machine.id}/target`, { configurationBaselineId: baseline.id, reason: '显式目标验收' })
      await write(`/api/v1/machines/${machine.id}/facts`, { operationType: 'InitialSnapshot', coverage: 'Full', sourceType: 'manual-ui', reason: '实际版本验收', items: [{ componentId: component.id, versionId: version.id, absent: false, knownInstalledAt: null }, { componentId: driver.id, versionId: d1.id, absent: false, knownInstalledAt: null }] })
    }
    await write(`/api/v1/machines/${b.id}`, { ...secondInput, status: 'ShortTermCip', expectedResumeAt: new Date(Date.now() + 86400000).toISOString(), reason: '状态筛选验收' }, 'PUT')
    await write(`/api/v1/component-versions/${v1.id}/safety`, { state: 'Blocked', reason: '匹配与风险独立验收' })
    const endpoint = `/api/v1/projects/${project.id}/machine-registry`
    const registry = await get(endpoint)
    assert.equal(registry.items.length, 3)
    assert(registry.items.every(machine => machine.projectId === project.id))
    const first = registry.items.find(machine => machine.id === a.id)
    const second = registry.items.find(machine => machine.id === b.id)
    const unknown = registry.items.find(machine => machine.id === c.id)
    assert.equal(first.matchStatus, 'Matched'); assert.equal(first.riskSeverity, 'Critical')
    assert.equal(second.matchStatus, 'Mismatch')
    assert.equal(first.targetBaselineId, baseline.id); assert.equal(second.targetBaselineId, baseline.id)
    assert(first.actualVersions.some(version => version.versionId === v1.id))
    assert(!second.actualVersions.some(version => version.versionId === v1.id), 'Target versions must never masquerade as actual versions')
    assert(second.actualVersions.some(version => version.versionId === v2.id))
    assert.deepEqual(first.chambers, [1, 6])
    assert.equal(unknown.targetBaselineId, null); assert.equal(unknown.matchStatus, 'Unknown')
    assert.equal(unknown.hasActualConfiguration, false); assert.deepEqual(unknown.actualVersions, [])
    assert.deepEqual(registry.targetBaselines.map(item => item.id), [baseline.id])
    assert.equal(registry.actualVersions.length, 3)
    const anonymous = await browser.newContext({ baseURL })
    assert.equal((await anonymous.request.get(endpoint)).status(), 401)
    await anonymous.close()
    assert.equal((await api.get(`/api/v1/projects/${randomUUID()}/machine-registry`)).status(), 404)

    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: '机台' }).click()
    const rows = page.locator('.machine-list-item')
    await page.getByRole('button', { name: /A 一号机/ }).waitFor()
    assert.equal(await rows.count(), 3)
    assert.equal(await page.locator('.machine-detail-panel:visible').count(), 0)
    assert.deepEqual(await page.locator('.machine-location-group h4').allTextContents(), ['上海', '深圳'])
    const filters = page.getByRole('group', { name: '机台筛选' })
    const reset = () => page.getByRole('button', { name: '清空机台筛选' }).click()
    await filters.getByLabel('站点 / 位置').selectOption('深圳')
    assert.equal(await rows.count(), 1); assert.match(await rows.first().textContent(), /C 三号机/)
    await reset()
    await filters.getByLabel('目标基线', { exact: true }).selectOption(baseline.id)
    assert.equal(await rows.count(), 2)
    await filters.getByLabel('实际组件', { exact: true }).selectOption(component.id)
    await filters.getByLabel('整机实际版本').selectOption(v2.id)
    assert.equal(await rows.count(), 1); assert.match(await rows.first().textContent(), /B 二号机/)
    await filters.getByLabel('实际组件', { exact: true }).selectOption(driver.id)
    assert.equal(await filters.getByLabel('整机实际版本').inputValue(), '')
    assert.equal(await rows.count(), 2)
    await reset()
    await filters.getByLabel('机台状态').selectOption('ShortTermCip')
    assert.equal(await rows.count(), 1); assert.match(await rows.first().textContent(), /B 二号机/)
    await reset()
    await filters.getByLabel('机台阶段').selectOption('T1')
    assert.equal(await rows.count(), 1); assert.match(await rows.first().textContent(), /A 一号机/)
    await reset()
    await filters.getByLabel('查找机台').fill('王工')
    assert.equal(await rows.count(), 1); assert.match(await rows.first().textContent(), /C 三号机/)
    await reset()
    await filters.getByLabel('关注项').selectOption('mismatch')
    assert.equal(await rows.count(), 1); assert.match(await rows.first().textContent(), /B 二号机/)
    await filters.getByLabel('关注项').selectOption('no-target')
    assert.equal(await rows.count(), 1); assert.match(await rows.first().textContent(), /C 三号机/)
    await reset()
    const frame = await rows.evaluateAll(elements => elements.map(element => ({ top: element.getBoundingClientRect().top, bottom: element.getBoundingClientRect().bottom, width: element.getBoundingClientRect().width })))
    assert(frame[1].top >= frame[0].bottom - 1, 'Each machine occupies its own full-width row')
    assert(frame.every(row => row.width > 900))
    mkdirSync('artifacts/machine-registry', { recursive: true })
    await page.screenshot({ path: 'artifacts/machine-registry/desktop.png', fullPage: true })
    await page.getByRole('button', { name: /A 一号机/ }).click()
    await page.locator('.machine-detail-panel:visible').waitFor()
    assert.equal(await rows.count(), 3)
    await page.getByRole('button', { name: '返回机台列表' }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile page must not overflow horizontally')
    await page.screenshot({ path: 'artifacts/machine-registry/mobile.png', fullPage: true })
    assert.deepEqual(errors, [])
    console.log('Machine registry acceptance passed: project scope, target/actual separation, filters, independent Match/Risk, desktop rows, mobile and details.')
  } finally {
    for (const projectId of projects) await api.post(`/api/v1/projects/${projectId}/archive`, { data: { reason: '机台列表自动验收结束' }, headers: { 'Idempotency-Key': randomUUID() } }).catch(() => {})
    await context.close()
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
