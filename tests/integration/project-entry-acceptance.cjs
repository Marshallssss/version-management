const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL: process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080', viewport: { width: 1440, height: 1000 } })
  const write = async (url, data, method = 'POST') => {
    const response = await context.request.fetch(url, { method, data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), url + ': ' + await response.text())
    return response.status() === 204 ? null : response.json()
  }
  let project
  const page = await context.newPage()
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    project = await write('/api/v1/projects', { code: 'ENTRY-' + randomUUID().slice(0, 8), name: '按需录入验收', reason: '验收' })
    const component = await write(`/api/v1/projects/${project.id}/components`, { name: '控制程序', reason: '验收' })
    await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V1', maturity: 'Released', reason: '验收' })
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: /^版本$/ }).click()
    await page.locator('.root-node').first().click()
    const inspector = page.locator('.component-inspector')
    assert.equal(await inspector.locator('form:visible').count(), 0)
    await inspector.getByRole('button', { name: '登记新版本', exact: true }).click()
    await inspector.getByLabel('版本号', { exact: true }).fill('V1')
    await inspector.getByLabel('登记原因', { exact: true }).fill('重复登记应保留输入')
    await inspector.getByRole('button', { name: '登记测试中版本' }).click()
    await inspector.locator('.error-strip:visible').waitFor()
    assert.equal(await inspector.getByLabel('版本号', { exact: true }).inputValue(), 'V1')
    await inspector.getByRole('button', { name: '取消登记版本' }).click()
    assert.equal(await inspector.locator('form:visible').count(), 0)
    await inspector.getByRole('button', { name: '登记新版本', exact: true }).click()
    assert.equal(await inspector.getByLabel('版本号', { exact: true }).inputValue(), 'V1')
    await inspector.getByLabel('版本号', { exact: true }).fill('V2')
    await inspector.getByRole('button', { name: '登记测试中版本' }).click()
    await page.getByText('测试中版本已登记。', { exact: true }).waitFor()
    await inspector.getByRole('button', { name: '补丁', exact: true }).click()
    await inspector.getByRole('button', { name: '登记补丁', exact: true }).click()
    await inspector.getByLabel('补丁编号').fill('1.2')
    await inspector.getByLabel('补丁标题').fill('启动稳定性修复')
    await inspector.getByLabel('问题说明').fill('启动偶发失败')
    await inspector.getByLabel('修复说明').fill('增加启动重试')
    await inspector.getByRole('button', { name: '取消登记补丁' }).click()
    assert.equal(await inspector.locator('form:visible').count(), 0)
    await inspector.getByRole('button', { name: '登记补丁', exact: true }).click()
    assert.equal(await inspector.getByLabel('补丁编号').inputValue(), '1.2')
    await inspector.getByRole('button', { name: '登记补丁', exact: true }).click()
    await inspector.locator('.patch-list').getByText('1.2 · 启动稳定性修复', { exact: true }).waitFor()
    assert.equal(await inspector.locator('form:visible').count(), 0)
    const detail = await (await context.request.get(`/api/v1/projects/${project.id}`)).json()
    const version = detail.components[0].versions.find(item => item.versionNumber === 'V2')
    assert.equal(version.patchCount, 1)
    const machine = await write('/api/v1/machines', { projectId: project.id, serialNumber: 'PM-' + randomUUID().slice(0, 8), name: 'PM 验收机台', chambers: [{ number: 1, stage: 'Lab' }], reason: '验收' })
    await write(`/api/v1/machines/${machine.id}/chambers/1/configuration`, { items: [{ componentId: component.id, versionId: version.id }], reason: 'PM 界面追溯' }, 'PUT')
    await inspector.getByRole('button', { name: '影响', exact: true }).click()
    await page.getByRole('button', { name: '查看机台 PM 验收机台' }).waitFor()
    mkdirSync('artifacts/project-entry', { recursive: true })
    await page.screenshot({ path: 'artifacts/project-entry/pm-impact.png', fullPage: true })
    await page.getByRole('button', { name: '查看机台 PM 验收机台' }).click()
    await page.locator('.machine-detail-header').getByText('PM 验收机台', { exact: true }).waitFor()
    console.log('Project entry passed: existing information first, on-demand forms, cancel/reopen, validation retention, successful version/patch registration and PM impact navigation.')
  } catch (error) {
    mkdirSync('artifacts/project-entry', { recursive: true })
    await page.screenshot({ path: 'artifacts/project-entry/failure.png', fullPage: true })
    throw error
  } finally {
    if (project) await write(`/api/v1/projects/${project.id}/archive`, { reason: '录入验收结束' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1 })
