const { chromium } = require('playwright')
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs')
const { execFileSync } = require('node:child_process')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL: process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080', viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Shanghai' })
  const api = context.request
  const reason = '历史基线真实 Excel 验收'
  const call = (url, data, key = randomUUID(), client = api) => client.post(url, { data, headers: { 'Idempotency-Key': key } })
  const read = async response => { assert(response.ok(), `${response.url()}: ${await response.text()}`); return response.status() === 204 ? null : response.json() }
  const write = async (url, data) => read(await call(url, data))
  const get = async url => read(await api.get(url))
  const output = path.resolve('artifacts/historical-import')
  mkdirSync(output, { recursive: true })
  const workbook = path.join(output, 'history.xlsx')
  const fixture = (changes = {}, target = workbook) => JSON.parse(execFileSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', path.resolve('tests/integration/matrix-workbook-fixture.ps1'), '-Path', target, '-CellsJson', JSON.stringify(changes)], { encoding: 'utf8', windowsHide: true }).replace(/^\uFEFF/, ''))
  let project, secondaryProject, page
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const token = randomUUID().slice(0, 8)
    project = await write('/api/v1/projects', { code: `HISTORY-${token}`, name: '历史配置归档验收', reason })
    const component = (name, parentComponentId) => write(`/api/v1/projects/${project.id}/components`, { name, parentComponentId, reason })
    const root = await component('控制系统'), a = await component('主控软件', root.id), b = await component('驱动软件', root.id), c = await component('界面软件')
    const version = (item, versionNumber, maturity = 'Released') => write(`/api/v1/components/${item.id}/versions`, { versionNumber, maturity, reason })
    const aLive = await version(a, 'A.LIVE'), bLive = await version(b, 'B.LIVE'), cLive = await version(c, 'C.LIVE')
    const standard = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'LIVE', baselineCode: '当前正式配置', publishImmediately: true, reason })
    await write(`/api/v1/projects/${project.id}/standard`, { configurationBaselineId: standard.id, reason })
    const aTest = await version(a, 'A.TEST', 'Testing')
    const bad = await version(b, 'B.OLD', 'Deprecated')
    await write(`/api/v1/component-versions/${bad.id}/safety`, { state: 'Blocked', reason })
    const machine = await write('/api/v1/machines', { projectId: project.id, name: '历史导入隔离机台', serialNumber: `HISTORY-${token}`, stage: 'Lab', reason })
    await write(`/api/v1/machines/${machine.id}/target`, { configurationBaselineId: standard.id, reason })
    await write(`/api/v1/machines/${machine.id}/facts`, { operationType: 'InitialSnapshot', coverage: 'Full', sourceType: 'acceptance', effectiveAt: new Date().toISOString(), reason, items: [{ componentId: a.id, versionId: aLive.id }, { componentId: b.id, versionId: bLive.id }, { componentId: c.id, versionId: cLive.id }] })
    const actualBefore = await get(`/api/v1/machines/${machine.id}/configuration`)
    const projectBefore = await get(`/api/v1/projects/${project.id}`)
    const route = `/api/v1/projects/${project.id}/matrix-import`
    const template = await write(`${route}/templates`, { reason, supportsHistory: true })
    const original = await (await api.get(template.downloadUrl)).body()
    writeFileSync(workbook, original)
    const legacyTemplate = await write(`${route}/templates`, { reason, supportsHistory: false })
    const legacyWorkbook = path.join(output, 'legacy.xlsx')
    const legacyBytes = await (await api.get(legacyTemplate.downloadUrl)).body()
    writeFileSync(legacyWorkbook, legacyBytes)
    assert.equal(fixture({}, legacyWorkbook).A1, `ConfigHub.Matrix.v2:${legacyTemplate.id}`, '旧模板保持 v2 格式，不能伪装为历史模板')
    const legacyBody = { templateId: legacyTemplate.id, fileName: 'legacy.xlsx', contentBase64: legacyBytes.toString('base64'), reason }
    assert.equal((await call(`${route}/history/preview`, legacyBody)).status(), 400, '旧模板不允许进入历史基线预览')
    const cells = fixture()
    const row = item => Object.entries(cells).find(([k, v]) => /^A\d+$/.test(k) && v === item.id)[0].slice(1)
    assert.equal(cells.A1, `ConfigHub.Matrix.v3:${template.id}`)
    assert.equal(cells.__layout.freeze, 'D10')
    assert.equal(cells.D4, '配置记录 1')
    const input = {
      D6: '历史首次评审记录', D7: '历史基线', D8: '历史配置 2020', D9: '2020-01-02 08:30', [`D${row(a)}`]: '001.02', [`D${row(b)}`]: 'B.OLD', [`D${row(c)}`]: '当时未配置',
      E6: '历史第二次评审记录', E7: '历史基线', E8: '历史配置 2021', E9: '2021-02-03 10:00', [`E${row(a)}`]: '001.02', [`E${row(b)}`]: 'B.OLD', [`E${row(c)}`]: 'C.OLD',
      F5: '2026-09-22', F6: '历史列之后的测试增量', [`F${row(a)}`]: 'A.NEXT'
    }
    const body = () => ({ templateId: template.id, fileName: 'history.xlsx', contentBase64: readFileSync(workbook).toString('base64'), reason })
    const reset = changes => { writeFileSync(workbook, original); fixture({ ...input, ...changes }) }
    reset({})
    assert.equal((await write(`${route}/scan`, body())).status, 'Failed')
    assert.deepEqual((await get(`/api/v1/projects/${project.id}`)).components, projectBefore.components)
    for (const changes of [{ [`D${row(a)}`]: '' }, { D9: '2100-01-01 00:00' }, { D8: '当前正式配置' }, { D7: '测试版本' }, { D9: { numeric: 45600 } }, { [`E${row(b)}`]: '' }]) {
      reset(changes)
      assert.equal((await call(`${route}/history/preview`, body())).status(), 400, JSON.stringify(changes))
    }
    assert.deepEqual((await get(`/api/v1/projects/${project.id}`)).components, projectBefore.components)
    reset({})
    const preview = await write(`${route}/history/preview`, body())
    const foreign = await write('/api/v1/projects', { code: `OTHER-${token}`, name: '历史导入项目校验', reason })
    assert.equal((await call(`/api/v1/projects/${foreign.id}/matrix-import/history/preview`, body())).status(), 404)
    assert.equal((await call(`/api/v1/projects/${foreign.id}/matrix-import/history/${preview.id}/commit`, { reason })).status(), 404)
    await call(`/api/v1/projects/${foreign.id}/archive`, { reason })
    assert.equal((await call(`/api/v1/imports/${preview.id}/commit`, { reason })).status(), 409, 'Legacy commands cannot commit historical preview payloads')
    assert.equal(preview.records.length, 2)
    assert.equal(preview.testingRecordCount, 1)
    assert(preview.records[0].items.some(i => i.willCreate && i.versionNumber === '001.02'))
    assert(preview.records[0].items.some(i => i.currentMaturity === 'Deprecated' && i.currentSafety === 'Blocked'))
    assert.equal((await get(`/api/v1/projects/${project.id}/baselines`)).length, 1, 'Preview does not create baselines')
    const username = `history-viewer-${token}`, password = randomUUID()
    await write('/api/v1/admin/users', { userName: username, password, displayName: '历史只读验收', role: 'Viewer', reason })
    const viewer = await browser.newContext({ baseURL: process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080' })
    await read(await viewer.request.post('/api/v1/auth/login', { data: { userName: username, password } }))
    assert.equal((await call(`${route}/history/preview`, body(), randomUUID(), viewer.request)).status(), 403)
    assert.equal((await call(`${route}/history/${preview.id}/commit`, { reason }, randomUUID(), viewer.request)).status(), 403)
    const adminName = `history-admin-${token}`, adminPassword = randomUUID()
    const admin = await write('/api/v1/admin/users', { userName: adminName, password: adminPassword, displayName: '历史补录管理员', role: 'Admin', reason })
    const adminContext = await browser.newContext({ baseURL: process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080' })
    await read(await adminContext.request.post('/api/v1/auth/login', { data: { userName: adminName, password: adminPassword } }))
    const key = randomUUID()
    const committed = await read(await call(`${route}/history/${preview.id}/commit`, { reason }, key, adminContext.request))
    await write(`/api/v1/admin/users/${admin.id}/role`, { role: 'SeniorEngineer', reason })
    assert.equal((await call(`${route}/history/${preview.id}/commit`, { reason }, key, adminContext.request)).status(), 403, 'Revoked permission is checked before replay')
    assert.deepEqual(await read(await call(`${route}/history/${preview.id}/commit`, { reason }, key)), committed)
    const old = await get(`/api/v1/baselines/${committed.records[0].baselineId}`)
    assert(old.baseline.isHistorical)
    assert.equal(old.baseline.state, 'Released')
    assert.equal(new Date(old.baseline.releasedAt).toISOString(), '2020-01-02T00:30:00.000Z')
    assert(new Date(old.baseline.createdAt).getFullYear() >= 2026)
    assert.equal(old.baseline.releaseRecordedAt, null)
    assert(old.items.some(i => i.componentId === c.id && i.notConfigured && i.versionId === null))
    assert(old.items.some(i => i.componentId === b.id && i.historicalVersionState === 'HistoricalReleased' && i.versionId === bad.id))
    const created = old.items.find(i => i.componentId === a.id)
    const createdVersion = (await get(`/api/v1/component-versions/${created.versionId}`)).version
    assert.equal(createdVersion.maturity, 'Released')
    assert.equal(new Date(createdVersion.createdAt).toISOString(), '2020-01-02T00:30:00.000Z')
    assert.equal((await get(`/api/v1/component-versions/${aTest.id}`)).version.maturity, 'Testing')
    assert.equal((await get(`/api/v1/component-versions/${bad.id}`)).version.maturity, 'Deprecated')
    assert.equal((await get(`/api/v1/component-versions/${bad.id}`)).version.safety, 'Blocked')
    assert.deepEqual(await get(`/api/v1/machines/${machine.id}/configuration`), actualBefore)
    assert.equal((await get(`/api/v1/projects/${project.id}/standard`)).baselineId, standard.id)
    const comparison = await get(`/api/v1/machines/${machine.id}/compare-baseline/${old.baseline.id}`)
    assert.equal(comparison.items.find(i => i.componentId === c.id).status, 'Extra')
    assert.equal(comparison.items.find(i => i.componentId === c.id).expectedVersionNumber, '当时未配置')
    await write(`/api/v1/machines/${machine.id}/facts`, { operationType: 'Observation', coverage: 'Partial', sourceType: 'acceptance', effectiveAt: new Date().toISOString(), reason, items: [{ componentId: c.id, absent: true }] })
    const absentComparison = await get(`/api/v1/machines/${machine.id}/compare-baseline/${old.baseline.id}`)
    assert.equal(absentComparison.items.find(i => i.componentId === c.id).status, 'Matched')
    assert.equal((await call(`/api/v1/baselines/${old.baseline.id}/withdraw-release`, { reason })).status(), 409)
    assert.equal((await api.delete(`/api/v1/component-versions/${created.versionId}`, { data: { reason }, headers: { 'Idempotency-Key': randomUUID() } })).status(), 409)
    const audit = await get(`/api/v1/audit?entityId=${created.versionId}`)
    assert(audit.some(x => x.action === 'HistoricalComponentVersionRegistered' && new Date(x.occurredAt).getFullYear() >= 2026))
    const scanned = await write(`${route}/scan`, body())
    assert.equal(scanned.status, 'Succeeded', JSON.stringify(scanned.messages))
    assert.equal(scanned.importedCount, 1)
    const combination = (await get(route)).combinations[0]
    assert.equal(combination.items.find(i => i.componentId === b.id).versionId, bLive.id, 'History must not alter testing inheritance')
    assert.equal(combination.items.find(i => i.componentId === c.id).versionId, cLive.id)
    assert.equal((await write(`${route}/scan`, body())).importedCount, 0)
    reset({ D7: '测试版本', D8: '', D9: '', D5: '2020-01-02' })
    assert.equal((await write(`${route}/scan`, body())).status, 'Failed', 'Historical columns cannot become testing records')
    reset({ F7: '历史基线', F8: '不能改写测试列', F9: '2020-01-02 08:30', [`F${row(b)}`]: 'B.OLD', [`F${row(c)}`]: 'C.OLD' })
    assert.equal((await call(`${route}/history/preview`, body())).status(), 400, 'Testing columns cannot become historical records')
    reset({ D8: '改写已导入历史' })
    assert.equal((await write(`${route}/scan`, body())).status, 'Failed')
    reset({})

    // Revalidation rejects changed live states instead of committing stale preview assumptions.
    const next = { ...input, D8: '待确认历史 2020', E8: '待确认历史 2021' }
    writeFileSync(workbook, original)
    fixture({ ...next, D1: `${template.id.replaceAll('-', '')}-0101`, E1: `${template.id.replaceAll('-', '')}-0102`, F5: '', F6: '', [`F${row(a)}`]: '' })
    const stale = await write(`${route}/history/preview`, body())
    await write(`/api/v1/component-versions/${bad.id}/safety`, { state: 'Clear', reason })
    assert.equal((await call(`${route}/history/${stale.id}/commit`, { reason })).status(), 409)
    await write(`/api/v1/component-versions/${bad.id}/safety`, { state: 'Blocked', reason })

    page = await context.newPage()
    await page.goto('/')
    await page.getByTitle('切换当前项目').click()
    await page.getByLabel('项目', { exact: true }).selectOption(project.id)
    await page.locator('.nav-item').filter({ hasText: /^版本导入$/ }).click()
    await page.getByLabel('项目模板', { exact: true }).selectOption(template.id)
    await page.getByLabel('填写后的 Excel 文件').setInputFiles(workbook)
    await page.getByLabel('本次录入原因').fill(reason)
    await page.getByRole('button', { name: '历史基线预览', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '历史基线导入' })
    await dialog.getByRole('button', { name: '校验并预览历史基线' }).click()
    await Promise.race([
      dialog.getByLabel('选择历史基线').waitFor(),
      dialog.getByRole('alert').waitFor().then(async () => { throw new Error(await dialog.getByRole('alert').innerText()) })
    ])
    await dialog.getByText('当时未配置', { exact: true }).waitFor()
    await page.screenshot({ animations: 'disabled', path: path.join(output, 'preview-desktop.png') })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ animations: 'disabled', path: path.join(output, 'preview-mobile.png') })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: '确认导入 2 条历史基线' }).click()
    await dialog.getByText('历史已录入。', { exact: false }).waitFor()
    await dialog.getByRole('button', { name: '查看基线快照' }).click()
    await page.getByText('历史补录快照', { exact: true }).waitFor()
    await page.screenshot({ animations: 'disabled', path: path.join(output, 'snapshot-mobile.png') })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.screenshot({ animations: 'disabled', path: path.join(output, 'snapshot-desktop.png') })
    await component('新增模板外组件')
    writeFileSync(workbook, original)
    fixture({ ...input, D1: `${template.id.replaceAll('-', '')}-0201`, E1: `${template.id.replaceAll('-', '')}-0202`, D8: '旧组件树 2020', E8: '旧组件树 2021' })
    assert.equal((await call(`${route}/history/preview`, body())).status(), 400, 'Stale component trees are rejected before any business writes')
    console.log('Historical import passed: v3 XLSX, full scope and date validation, absent semantics, admin-only preview/commit, historical version backfill/time, preserved Testing/risk/standard/machine, isolated mixed inheritance, immutable history/replay, stale preview rejection and real desktop/mobile confirmation.')
  } finally {
    if (project) await call(`/api/v1/projects/${project.id}/archive`, { reason: '历史导入验收结束' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
