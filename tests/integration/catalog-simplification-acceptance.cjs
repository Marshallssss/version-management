const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')

async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL: process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080', viewport: { width: 1440, height: 1000 } })
  const api = context.request
  const call = (url, data, method = 'POST', key = randomUUID()) => api.fetch(url, { method, data, headers: { 'Idempotency-Key': key } })
  const write = async (url, data, method = 'POST') => { const r = await call(url, data, method); assert(r.ok(), url + ': ' + await r.text()); return r.status() === 204 ? null : r.json() }
  const get = async url => { const r = await api.get(url); assert(r.ok(), await r.text()); return r.json() }
  const projects = []; let page
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const code = 'PROJECT SPACE ' + randomUUID().slice(0, 8)
    const project = await write('/api/v1/projects', { code, name: '录入与基线简化验收', reason: '验收' }); projects.push(project.id)
    assert.equal((await call('/api/v1/projects', { code: ' ' + code.toLowerCase() + ' ', name: '重复', reason: '验收' })).status(), 409)
    const root = await write(`/api/v1/projects/${project.id}/components`, { name: '工艺系统', owner: '张工', model: 'CTRL 200', notes: '结构分类节点\n接口约定', reason: '验收' })
    const child = await write(`/api/v1/projects/${project.id}/components`, { name: '下位机控制软件', parentComponentId: root.id, reason: '验收' })
    const sibling = await write(`/api/v1/projects/${project.id}/components`, { name: '驱动模块', parentComponentId: root.id, reason: '验收' })
    const version = (id, number, maturity = 'Testing') => write(`/api/v1/components/${id}/versions`, { versionNumber: number, maturity, reason: '验收' })
    const a1 = await version(child.id, 'V1.0', 'Released'); const b1 = await version(sibling.id, 'D1.0', 'Released')
    await write(`/api/v1/component-versions/${a1.id}/patches`, { patchCode: '1.2.3', title: '点分补丁', issueDescription: '问题', resolutionDescription: '修复', status: 'Released' })
    assert((await get('/api/v1/search?query=1.2.3')).some(x => x.type === 'Patch'))
    const old = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: code, baselineCode: 'BASE 1.0', reason: '首次直接发布', publishImmediately: true })
    const oldDetail = await get(`/api/v1/baselines/${old.id}`)
    assert.equal(oldDetail.baseline.state, 'Released'); assert.equal(oldDetail.review, null)
    const draft = await write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: code, baselineCode: 'LEGACY DRAFT', reason: '旧草稿验收' })
    for (const action of ['review', 'review/approve']) await write(`/api/v1/baselines/${draft.id}/${action}`, { reason: '旧流程验收' })
    await write(`/api/v1/projects/${project.id}/standard`, { configurationBaselineId: old.id, reason: '显式标准' })
    const machine = await write('/api/v1/machines', { projectId: project.id, serialNumber: randomUUID(), name: '旧目标机台', reason: '验收' })
    await write(`/api/v1/machines/${machine.id}/target`, { configurationBaselineId: old.id, reason: '旧目标固定' })
    const a2 = await version(child.id, 'V2.0')
    await write(`/api/v1/component-versions/${a1.id}/recommend`, { reason: '原推荐' })
    await write(`/api/v1/component-versions/${a1.id}/maturity`, { state: 'Testing', reason: '发布后重新调测' })
    assert.equal((await call(`/api/v1/baselines/${draft.id}/release`, { reason: '不可发布已返回测试的草稿' })).status(), 409)
    let detail = await get(`/api/v1/projects/${project.id}`)
    assert.equal(detail.components.find(x => x.id === child.id).versions.find(x => x.id === a2.id).maturity, 'Deprecated')
    assert.equal(detail.components.find(x => x.id === child.id).versions.find(x => x.id === a1.id).maturity, 'Testing')
    assert.deepEqual((await get(`/api/v1/baselines/${old.id}`)).items, oldDetail.items)
    const a3 = await version(child.id, 'V3.0.2026-Long-Version'); const b2 = await version(sibling.id, 'D2.0')
    const blockedInput = { seriesCode: code, baselineCode: 'BLOCKED.1', reason: '阻断不允许直接发布', testingVersionIds: [a3.id, b2.id], publishImmediately: true }
    assert.equal((await call(`/api/v1/projects/${project.id}/baselines`, { ...blockedInput, baselineCode: 'INVALID SELECTION', versionSelections: [{ componentId: child.id, versionId: a3.id }, { componentId: sibling.id, versionId: b1.id }] })).status(), 400)
    await write(`/api/v1/component-versions/${b2.id}/safety`, { state: 'Blocked', reason: '阻断验收' })
    assert.equal((await call(`/api/v1/projects/${project.id}/baselines`, blockedInput)).status(), 409)
    assert(!(await get(`/api/v1/projects/${project.id}/baselines`)).some(x => x.code === 'BLOCKED.1'))
    assert.equal((await get(`/api/v1/projects/${project.id}`)).components.find(x => x.id === child.id).versions.find(x => x.id === a3.id).maturity, 'Testing')
    await write(`/api/v1/component-versions/${b2.id}/safety`, { state: 'Clear', reason: '解除阻断' })
    const clone = await write(`/api/v1/projects/${project.id}/clone`, { code: code + ' CLONE', name: '克隆资料', reason: '验收' }); projects.push(clone.id)
    assert.equal((await get(`/api/v1/projects/${clone.id}`)).components.find(x => x.name === '工艺系统').model, 'CTRL 200')
    assert.equal((await call(`/api/v1/components/${root.id}`, { name: '工艺系统', notes: 'x'.repeat(2001), reason: '过长' }, 'PUT')).status(), 400)
    page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto('/'); await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id); await page.reload()
    await page.locator('.nav-item').filter({ hasText: /^版本$/ }).click()
    const testingNode = page.locator('.laboratory-tree .lab-node').filter({ hasText: '下位机控制软件' })
    await testingNode.waitFor()
    assert(await testingNode.evaluate(node => {
      const name = node.querySelector('span:first-child > strong').getBoundingClientRect()
      const version = node.querySelector('span:first-child > small').getBoundingClientRect()
      return version.top >= name.bottom - 1 && version.width > 0
    }), 'Laboratory names and versions must occupy separate rows')
    await page.locator('.root-node').filter({ hasText: '工艺系统' }).click()
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    const form = page.locator('.component-inspector form').first()
    await form.getByLabel('组件负责人').fill('李工'); await form.getByLabel('组件型号').fill('CTRL 300'); await form.getByLabel('组件备注').fill('更新接口约定')
    await form.getByLabel('修改原因').fill('界面维护组件资料'); await form.getByRole('button', { name: '保存组件' }).click()
    await page.getByText('CTRL 300', { exact: true }).waitFor()
    await page.getByRole('button', { name: '从测试版本创建基线', exact: true }).click()
    const composer = page.locator('#baseline-composer'); const parent = composer.getByRole('checkbox', { name: '选择 工艺系统 整个分支', exact: true })
    await parent.check()
    const childCheck = composer.getByRole('checkbox', { name: '选择版本 下位机控制软件 V3.0.2026-Long-Version', exact: true })
    assert(await childCheck.isChecked())
    await childCheck.uncheck(); assert(await parent.evaluate(e => e.indeterminate)); await parent.check()
    await composer.getByLabel('基线名称').fill('BASE 2.0'); await composer.getByLabel('创建原因').fill('一键发布并生成历史快照')
    mkdirSync('artifacts/catalog-simplification', { recursive: true })
    await page.screenshot({ path: 'artifacts/catalog-simplification/composer-desktop.png', fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 }); assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await composer.screenshot({ path: 'artifacts/catalog-simplification/composer-mobile.png' })
    const created = page.waitForResponse(r => r.url().endsWith(`/projects/${project.id}/baselines`) && r.request().method() === 'POST')
    await composer.getByRole('button', { name: '发布 2 个测试版本并创建基线', exact: true }).click()
    const response = await created; assert(response.ok(), await response.text()); const published = await response.json()
    const snapshot = await get(`/api/v1/baselines/${published.id}`)
    assert.equal(snapshot.baseline.state, 'Released'); assert.equal(snapshot.review, null)
    assert(snapshot.items.some(x => x.versionId === a3.id)); assert(snapshot.items.some(x => x.versionId === b2.id))
    assert.equal((await get(`/api/v1/machines/${machine.id}/target`)).baselineId, old.id)
    assert.equal((await get(`/api/v1/projects/${project.id}/standard`)).baselineId, old.id)
    const a4 = await version(child.id, 'V4.0'); const key = randomUUID()
    const input = { seriesCode: code, baselineCode: 'BASE 3.0', testingVersionIds: [a4.id], reason: '并发重放验收', publishImmediately: true }
    const results = await Promise.all([call(`/api/v1/projects/${project.id}/baselines`, input, 'POST', key), call(`/api/v1/projects/${project.id}/baselines`, input, 'POST', key)])
    for (const r of results) assert(r.ok(), await r.text())
    assert.equal((await results[0].json()).id, (await results[1].json()).id)
    assert.equal((await call(`/api/v1/projects/${project.id}/baselines`, { ...input, reason: '冲突' }, 'POST', key)).status(), 409)
    const audit = await get(`/api/v1/audit?entityId=${published.id}`)
    assert.equal(audit.filter(x => x.action === 'BaselineReleased').length, 1)
    assert(audit.every(x => x.actor && x.correlationId))
    assert.deepEqual(errors, [])
    console.log('Catalog simplification passed: spaced project code, dotted patch, component metadata/clone, return to testing, parent selection, atomic direct publish and fixed historical targets.')
  } catch (error) {
    if (page) { mkdirSync('artifacts/catalog-simplification', { recursive: true }); await page.screenshot({ path: 'artifacts/catalog-simplification/failure.png', fullPage: true }) }
    throw error
  } finally {
    for (const id of projects) await call(`/api/v1/projects/${id}/archive`, { reason: '验收清理' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
