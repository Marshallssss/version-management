const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const api = context.request
  const projects = []
  const output = path.resolve('artifacts/project-picker')
  mkdirSync(output, { recursive: true })
  const write = async (url, data, method = 'POST') => {
    const response = await api.fetch(url, { method, data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), `${url}: ${await response.text()}`)
    return response.status() === 204 ? null : response.json()
  }
  const token = randomUUID().slice(0, 8)
  let page
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const longName = '长名称项目跨团队生产设备软件版本与配置维护'.repeat(10).slice(0, 180)
    const longProject = await write('/api/v1/projects', { code: `PICKER-LONG-${token}`, name: longName, description: '长名称项目选择与下拉菜单验收', reason: '自动验收' })
    const shortProject = await write('/api/v1/projects', { code: `PICKER-SHORT-${token}`, name: `选择验收 ${token}`, reason: '自动验收' })
    projects.push(longProject.id, shortProject.id)
    const emptyStandard = await api.get(`/api/v1/projects/${longProject.id}/standard`)
    assert.equal(emptyStandard.status(), 204, 'A project without a standard must return No Content, not an empty JSON response')
    assert.equal(await emptyStandard.text(), '')
    const component = await write(`/api/v1/projects/${shortProject.id}/components`, { name: '控制软件', reason: '验收' })
    const version = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'PICKER.1', maturity: 'Testing', reason: '验收' })
    const machine = await write('/api/v1/machines', { projectId: shortProject.id, serialNumber: `PICKER-${token}`, name: '下拉菜单验收机台', location: '苏州实验室', stage: 'Lab', reason: '验收' })

    page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', async response => {
      if (response.status() >= 500 && response.url().includes('/api/')) console.warn(`API ${response.status()} ${new URL(response.url()).pathname}: ${(await response.text().catch(() => '')).slice(0, 1000)}`)
    })
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), longProject.id)
    await page.reload()
    await page.locator('.project-switch strong').filter({ hasText: longName }).waitFor()
    const standardSummary = page.locator('.overview-project-strip button').filter({ hasText: '当前项目标准' })
    await standardSummary.getByText('尚未设定', { exact: true }).waitFor()
    assert.doesNotMatch(await standardSummary.textContent(), /读取失败/, 'No project standard is an empty state, not a loading failure')
    assert(await page.evaluate(() => CSS.supports('appearance', 'base-select')), 'The current Edge acceptance environment must exercise the customizable picker, not the fallback')
    const picker = () => page.getByRole('dialog').getByLabel('项目', { exact: true })
    const openProjects = async () => {
      await page.locator('.project-switch').click()
      await picker().waitFor()
      await picker().hover()
      await page.waitForFunction(element => element.getBoundingClientRect().width >= parseFloat(getComputedStyle(element).width) - 1, await page.getByRole('dialog').elementHandle())
    }
    const openPicker = async select => {
      await select.click()
      await page.waitForFunction(element => element.matches(':open'), await select.elementHandle())
      assert.equal(await select.evaluate(element => getComputedStyle(element).appearance), 'base-select')
      assert.equal(await select.evaluate(element => getComputedStyle(element, '::picker(select)').backgroundColor), 'rgb(255, 255, 255)')
    }
    const assertPickerWidth = async select => {
      const control = await select.boundingBox()
      const menuWidth = await select.evaluate(element => parseFloat(getComputedStyle(element, '::picker(select)').width))
      assert(menuWidth <= control.width + 2 && menuWidth >= control.width - 2, `Wide picker should match its control instead of expanding for long options: ${menuWidth} / ${control.width}`)
    }
    const assertOptionFits = async option => {
      await option.scrollIntoViewIfNeeded()
      const rect = await option.boundingBox()
      assert(rect && rect.width > 0, 'The real picker option must be visible')
      assert(rect.x >= -1 && rect.x + rect.width <= page.viewportSize().width + 1, `Option must fit horizontally: ${JSON.stringify(rect)}`)
    }

    await openProjects()
    const dialog = await page.getByRole('dialog').boundingBox()
    const field = await picker().boundingBox()
    assert(dialog.width >= 900, `Desktop project selection must use the wider dialog: ${dialog.width}`)
    assert(field.width >= 820, 'Project selection must span the full form row')
    await openPicker(picker())
    await assertPickerWidth(picker())
    const selected = picker().locator(`option[value="${longProject.id}"]`)
    await assertOptionFits(selected)
    assert.equal(await selected.evaluate(element => getComputedStyle(element).color), 'rgb(40, 93, 229)')
    assert.equal(await selected.evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(237, 242, 255)')
    await page.screenshot({ path: path.join(output, 'project-desktop.png'), animations: 'disabled' })
    await picker().locator(`option[value="${shortProject.id}"]`).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => localStorage.getItem('confighub.selected-project-id')), shortProject.id)
    await page.reload()
    await page.locator('.project-switch strong').filter({ hasText: shortProject.name ?? `选择验收 ${token}` }).waitFor()

    await openProjects()
    const index = await picker().evaluate((element, id) => [...element.options].findIndex(option => option.value === id), longProject.id)
    assert(index > 0)
    await openPicker(picker())
    await page.keyboard.press('Home')
    for (let i = 0; i < index; i++) await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => localStorage.getItem('confighub.selected-project-id')), longProject.id, 'Keyboard project selection must persist')

    await page.setViewportSize({ width: 390, height: 844 })
    await openProjects()
    await openPicker(picker())
    await assertOptionFits(picker().locator(`option[value="${longProject.id}"]`))
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Project dialog must not cause mobile page overflow')
    await page.screenshot({ path: path.join(output, 'project-mobile.png'), animations: 'disabled' })
    await picker().locator(`option[value="${shortProject.id}"]`).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 1440, height: 1000 })

    await page.getByRole('button', { name: '新建项目', exact: true }).click()
    const clone = page.getByRole('dialog').getByLabel('创建方式')
    await openPicker(clone)
    await assertPickerWidth(clone)
    await assertOptionFits(clone.locator(`option[value="${longProject.id}"]`))
    await page.screenshot({ path: path.join(output, 'clone-picker.png'), animations: 'disabled' })
    await clone.locator(`option[value="${longProject.id}"]`).click()
    assert.equal(await clone.inputValue(), longProject.id)
    assert.equal(await page.getByRole('dialog').locator('textarea').inputValue(), '长名称项目选择与下拉菜单验收')
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click()

    await page.locator('.nav-item').filter({ hasText: /^机台$/ }).click()
    await page.getByRole('button', { name: /下拉菜单验收机台/ }).waitFor()
    const location = page.getByRole('group', { name: '机台筛选' }).getByLabel('站点 / 位置')
    await openPicker(location)
    await assertOptionFits(location.locator('option[value="苏州实验室"]'))
    await page.screenshot({ path: path.join(output, 'machine-filter.png'), animations: 'disabled' })
    await location.locator('option[value="苏州实验室"]').click()
    assert.equal(await location.inputValue(), '苏州实验室')
    assert.equal(await page.locator('.machine-list-item').count(), 1)
    await page.getByRole('button', { name: /下拉菜单验收机台/ }).click()
    await page.getByRole('button', { name: '记录局部观察', exact: true }).click()
    const observation = page.getByRole('dialog')
    const componentSelect = observation.getByLabel(/^组件/)
    const versionSelect = observation.getByLabel(/^版本/)
    assert(await versionSelect.isDisabled(), 'Dependent version selection remains disabled until choosing a component')
    assert.equal(await versionSelect.evaluate(element => getComputedStyle(element).cursor), 'not-allowed')
    assert.equal(await componentSelect.evaluate(element => element.validity.valueMissing), true, 'Required select validation must remain native')
    await observation.getByRole('button', { name: '记录局部观察', exact: true }).click()
    assert.equal(await componentSelect.evaluate(element => element.matches(':invalid')), true)
    await componentSelect.selectOption(component.id)
    assert(await versionSelect.isEnabled())
    assert.equal(await versionSelect.evaluate(element => element.validity.valueMissing), true)
    await versionSelect.selectOption(version.id)
    assert.equal(await versionSelect.evaluate(element => element.validity.valid), true)
    assert.equal((await api.get(`/api/v1/machines/${machine.id}/facts`).then(response => response.json())).length, 0, 'Invalid form attempts must not create observations')
    await page.screenshot({ path: path.join(output, 'native-validation.png'), animations: 'disabled' })
    assert.deepEqual(errors, [])
    console.log('Project picker passed: 180-character names, full-width desktop selection, real themed menus, mouse/keyboard persistence, 390px layout, clone/filter selectors and native required/disabled validation.')
  } catch (error) {
    if (page) await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
    throw error
  } finally {
    for (const id of projects) await write(`/api/v1/projects/${id}/archive`, { reason: '项目选择自动验收结束' }).catch(() => {})
    await context.close()
    await browser.close()
  }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1 })
