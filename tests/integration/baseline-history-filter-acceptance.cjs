const { execFileSync } = require('node:child_process')
const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Shanghai' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const output = path.resolve('artifacts/baseline-history-filters')
  mkdirSync(output, { recursive: true })
  const fixtures = []
  const write = async (url, data, method = 'post', client = context.request) => {
    const response = await client[method](url, { data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), `${url}: ${await response.text()}`)
    return response.status() === 204 ? null : response.json()
  }
  const get = async (url, client = context.request) => {
    const response = await client.get(url)
    assert(response.ok(), `${url}: ${await response.text()}`)
    return response.json()
  }
  const countRows = async expected => {
    await page.waitForFunction(count => document.querySelectorAll('.baseline-timeline .timeline-item').length === count, expected)
  }
  const openHistory = async (target, projectId) => {
    await target.goto('/')
    await target.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), projectId)
    await target.reload()
    await target.locator('.nav-item').filter({ hasText: /^基线$/ }).click()
    await target.getByRole('heading', { name: '基线历史' }).waitFor()
  }
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const token = randomUUID().slice(0, 8)
    const project = await write('/api/v1/projects', { code: 'BASELINE-FILTER-' + token, name: '基线历史筛选验收', reason: '自动化验收' })
    fixtures.push(project)
    const empty = await write('/api/v1/projects', { code: 'BASELINE-EMPTY-' + token, name: '空基线项目', reason: '自动化验收' })
    fixtures.push(empty)
    const root = await write(`/api/v1/projects/${project.id}/components`, { name: '控制系统', reason: '验收' })
    const component = name => write(`/api/v1/projects/${project.id}/components`, { name, parentComponentId: root.id, reason: '验收' })
    const control = await component('主控制组件')
    const driver = await component('驱动组件')
    const version = (owner, number) => write(`/api/v1/components/${owner.id}/versions`, { versionNumber: number, maturity: 'Released', reason: '验收' })
    const a1 = await version(control, 'A1-frozen')
    const a2 = await version(control, 'A2-frozen')
    const b1 = await version(driver, 'B1')
    const b2 = await version(driver, 'B2')
    const baseline = async (code, a, b, createdAt) => {
      const result = await write(`/api/v1/projects/${project.id}/baselines`, {
        seriesCode: 'HISTORY', baselineCode: code, publishImmediately: true, reason: '历史筛选验收',
        versionSelections: [{ componentId: control.id, versionId: a.id }, { componentId: driver.id, versionId: b.id }]
      })
      await write(`/api/v1/baselines/${result.id}/maintenance`, { createdAt, maintenanceMode: true, reason: '仅构造验收项目历史录入时间' })
      execFileSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', path.resolve('tests/integration/baseline-metadata-fixture.ps1'), '-BaselineId', result.id, '-ReleasedAt', createdAt], { windowsHide: true })
      return result
    }
    const oldest = await baseline('历史-01', a1, b1, '2020-01-10T00:01:00+08:00')
    const middle = await baseline('历史-02', a2, b1, '2020-01-15T23:59:59+08:00')
    const newest = await baseline('历史-03', a2, b2, '2020-01-20T00:01:00+08:00')
    await write(`/api/v1/projects/${project.id}/standard`, { configurationBaselineId: middle.id, reason: '标准不一定是最新快照' })
    const frozen = await Promise.all([oldest, middle, newest].map(item => get(`/api/v1/baselines/${item.id}`)))
    const versionDetail = await get(`/api/v1/component-versions/${a2.id}`)
    await write(`/api/v1/component-versions/${a2.id}/maintenance`, { versionNumber: 'A2-renamed', maturity: 'Released', createdAt: versionDetail.version.createdAt, maintenanceMode: true, reason: '更名不能篡改冻结筛选' })
    await write(`/api/v1/components/${control.id}`, { name: '主控制组件现用名称', reason: '历史名称冻结' }, 'put')
    const indexPath = `/api/v1/projects/${project.id}/baseline-history-index`
    const index = await get(indexPath)
    assert.deepEqual(index.map(item => item.id), [newest.id, middle.id, oldest.id])
    assert.equal(index[0].items.find(item => item.componentId === control.id).componentName, '主控制组件')
    assert.equal(index[0].items.find(item => item.componentId === control.id).versionNumber, 'A2-frozen')
    assert.deepEqual(await get(`/api/v1/projects/${empty.id}/baseline-history-index`), [])
    assert.equal((await context.request.get(`/api/v1/projects/${randomUUID()}/baseline-history-index`)).status(), 404)
    const anonymous = await browser.newContext({ baseURL })
    assert.equal((await anonymous.request.get(indexPath)).status(), 401)
    await anonymous.close()
    const protectedDelete = await context.request.delete(`/api/v1/component-versions/${a2.id}`, { data: { reason: '验证历史保护' }, headers: { 'Idempotency-Key': randomUUID() } })
    assert.equal(protectedDelete.status(), 409, 'Historical filtering must not weaken version reference protection')

    const requests = []
    page.on('request', request => requests.push(new URL(request.url()).pathname))
    await openHistory(page, project.id)
    await countRows(3)
    await page.locator('.baseline-snapshot h3').filter({ hasText: '历史-03' }).waitFor()
    assert.deepEqual(await page.locator('.timeline-item > strong').allTextContents(), ['历史-03', '历史-02', '历史-01'])
    const standard = page.locator('.timeline-item').filter({ hasText: '历史-02' })
    assert.equal(await standard.locator('.standard-mark').innerText(), '项目标准')
    assert.equal(await page.locator('.timeline-item .standard-mark').count(), 1)
    await standard.click()
    await page.locator('.snapshot-heading .standard-mark').waitFor()
    assert.equal(await page.locator('.snapshot-heading .standard-mark').innerText(), '当前项目标准')
    assert.equal(requests.filter(url => url === indexPath).length, 1)
    assert(requests.filter(url => /^\/api\/v1\/baselines\/[a-f0-9-]+$/.test(url)).length <= 2, 'History entry must not load every baseline detail')
    await page.getByLabel('基线时间排序').selectOption('oldest')
    assert.deepEqual(await page.locator('.timeline-item > strong').allTextContents(), ['历史-01', '历史-02', '历史-03'])
    await page.getByLabel('基线开始日期').fill('2020-01-15')
    await page.getByLabel('基线结束日期').fill('2020-01-15')
    await countRows(1)
    assert.equal(await page.locator('.timeline-item > strong').innerText(), '历史-02', 'End date must include 23:59:59 in local time')
    await page.getByRole('button', { name: '清除筛选', exact: true }).click()
    await countRows(3)
    await page.getByRole('button', { name: '组件版本', exact: true }).click()
    await page.getByLabel('筛选组件 1', { exact: true }).selectOption(control.id)
    assert(!(await page.getByLabel('筛选组件 1', { exact: true }).innerText()).includes('现用名称'))
    assert(!(await page.getByLabel('筛选版本 1', { exact: true }).innerText()).includes('A2-renamed'))
    await page.getByLabel('筛选版本 1', { exact: true }).selectOption({ label: 'A2-frozen' })
    await countRows(2)
    await page.locator('.timeline-item').filter({ hasText: '历史-03' }).click()
    await page.locator('.baseline-difference h4').filter({ hasText: '相对于 历史-02' }).waitFor()
    await page.getByRole('button', { name: '组件版本', exact: true }).click()
    await page.getByLabel('筛选组件 2', { exact: true }).selectOption(driver.id)
    await page.getByLabel('筛选版本 2', { exact: true }).selectOption({ label: 'B2' })
    await countRows(1)
    assert.equal(await page.locator('.timeline-item > strong').innerText(), '历史-03')
    await page.locator('.baseline-difference h4').filter({ hasText: '相对于 历史-02' }).waitFor()
    assert.equal(await page.locator('.timeline-item').filter({ hasText: '历史-02' }).count(), 0, 'Comparison predecessor must remain the complete chronological predecessor, even when filtered out')
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.locator('.baseline-history-filters').scrollIntoViewIfNeeded()
      await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth + 1)
      await page.screenshot({ path: path.join(output, `history-${width}.png`), animations: 'disabled', fullPage: true })
    }
    await page.getByLabel('筛选版本 1', { exact: true }).selectOption({ label: 'A1-frozen' })
    await countRows(0)
    await page.getByText('没有符合筛选条件的基线。', { exact: true }).waitFor()
    await page.getByRole('button', { name: '清除筛选', exact: true }).click()
    await countRows(3)
    await page.getByLabel('基线开始日期').fill('2021-02-01')
    await page.getByLabel('基线结束日期').fill('2020-01-01')
    await page.getByText('开始日期不能晚于结束日期。', { exact: true }).waitFor()
    await page.getByRole('button', { name: '清除筛选', exact: true }).click()

    // Freeze-based filtering still works when the current component catalog is unavailable.
    const catalog = await get(`/api/v1/projects/${project.id}`)
    await page.route(`**/api/v1/projects/${project.id}`, route => route.fulfill({ json: { ...catalog, components: [] } }))
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: /^基线$/ }).click()
    await countRows(3)
    await page.getByRole('button', { name: '组件版本', exact: true }).click()
    await page.getByLabel('筛选组件 1', { exact: true }).selectOption(control.id)
    await page.getByLabel('筛选版本 1', { exact: true }).selectOption({ label: 'A2-frozen' })
    await countRows(2)
    await page.unroute(`**/api/v1/projects/${project.id}`)
    await openHistory(page, empty.id)
    await page.getByText('暂无基线，可从测试版本创建。', { exact: true }).waitFor()
    await page.getByRole('button', { name: '从测试版本创建基线', exact: true }).click()
    await page.locator('#baseline-composer').waitFor()

    await page.route('**/baseline-history-index', route => route.fulfill({ status: 500, json: { message: '验收暂时不可用' } }))
    await openHistory(page, project.id)
    await page.getByText('基线历史加载失败：验收暂时不可用', { exact: true }).waitFor({ timeout: 20000 })
    await page.unroute('**/baseline-history-index')
    await page.getByRole('button', { name: '重试', exact: true }).click()
    await countRows(3)
    const userName = 'baseline-viewer-' + token
    const password = randomUUID()
    await write('/api/v1/admin/users', { userName, displayName: '基线筛选只读验收', password, role: 'Viewer', reason: '自动化验收' })
    const viewer = await browser.newContext({ baseURL, timezoneId: 'Asia/Shanghai' })
    await write('/api/v1/auth/login', { userName, password }, 'post', viewer.request)
    assert.equal((await get(indexPath, viewer.request)).length, 3)
    const viewerPage = await viewer.newPage()
    await openHistory(viewerPage, project.id)
    await viewerPage.locator('.timeline-item').first().waitFor()
    assert.equal(await viewerPage.getByRole('button', { name: '从测试版本创建基线', exact: true }).count(), 0)
    assert.equal(await viewerPage.getByRole('button', { name: '历史维护', exact: true }).count(), 0)
    assert(await viewerPage.getByLabel('基线开始日期').isVisible())
    await viewer.close()
    assert.deepEqual(await Promise.all([oldest, middle, newest].map(item => get(`/api/v1/baselines/${item.id}`))), frozen)
    assert.deepEqual(errors, [])
    console.log('Baseline history acceptance passed: authenticated project scope, frozen-name index, local inclusive date range, AND version filters, ordering, standard tags, complete-timeline comparison, read-only Viewer, retry, empty states and responsive layouts.')
  } finally {
    for (const project of fixtures) await write(`/api/v1/projects/${project.id}/archive`, { reason: '自动化验收结束' }).catch(() => {})
    await browser.close()
  }
}

main().catch(error => { console.error(error.stack); process.exitCode = 1 })
