const { chromium } = require('playwright')
const { readFileSync, mkdirSync, writeFileSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  page.setDefaultTimeout(15000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const output = path.resolve('artifacts/future-ui')
  mkdirSync(output, { recursive: true })
  let project
  const screenshots = []
  const write = async (url, data) => {
    const response = await context.request.post(url, { data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), url + ': ' + await response.text())
    return response.status() === 204 ? null : response.json()
  }
  const get = async url => {
    const response = await context.request.get(url)
    assert(response.ok(), url + ': ' + await response.text())
    return response.json()
  }
  const capture = async (name, width = 1440, target = page) => {
    await target.setViewportSize({ width, height: 1000 })
    await target.waitForFunction(() => document.fonts.status === 'loaded')
    await target.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    assert(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), name + ' document overflow')
    const dialog = target.getByRole('dialog')
    if (await dialog.isVisible()) {
      await target.waitForFunction(() => [...document.querySelectorAll('[role="dialog"]')].filter(element => element.getBoundingClientRect().width).every(element => getComputedStyle(element).opacity === '1' && !/ant-zoom-(appear|enter)/.test(element.className)))
      const box = await dialog.boundingBox()
      assert(box && box.x >= -1 && box.x + box.width <= width + 1 && box.y >= -1 && box.y < 1000, name + ' dialog overflow')
    }
    const file = name + '-' + width + '.png'
    await target.screenshot({ path: path.join(output, file), animations: 'disabled', fullPage: !await dialog.isVisible() && !['users', 'baseline-history'].includes(name) })
    screenshots.push(file)
  }
  const nav = async name => {
    await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name, exact: true }).click()
    await page.getByRole('heading', { level: 1, name, exact: true }).waitFor()
  }
  const machineTab = async name => {
    const button = page.getByRole('navigation', { name: '机台详情' }).getByRole('button', { name, exact: true })
    await button.click()
    await page.waitForFunction(label => [...document.querySelectorAll('.workspace-tabs button')].some(button => button.textContent === label && button.getAttribute('aria-pressed') === 'true'), name)
  }
  try {
    await page.goto('/')
    await page.locator('.topbar').getByRole('button', { name: '登录', exact: true }).click()
    await page.getByRole('dialog').getByLabel('用户名').fill(config.ConfigHub.BootstrapAdmin.Email)
    await page.getByRole('dialog').getByLabel('密码').fill(config.ConfigHub.BootstrapAdmin.Password)
    await capture('login')
    await page.getByRole('dialog').getByRole('button', { name: '登录', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    const token = randomUUID().slice(0, 8)
    const viewerName = 'future-viewer-' + token
    const viewerPassword = 'Viewer-' + randomUUID()
    project = await write('/api/v1/projects', { code: 'FUTURE-' + token, name: '先进工艺平台 · 软件配置管理', description: '实验室验证 / 产线交付 / 多腔室配置追溯', reason: 'UI 自动化验收' })
    const components = []
    const released = []
    const testing = []
    for (const [index, names] of [['主控系统', '设备控制服务', '工艺配方引擎'], ['下位机系统', '运动控制器', '真空传输控制'], ['工艺腔室', '温度控制模块', '射频电源控制'], ['设备集成', '数据采集服务', '视觉检测组件']].entries()) {
      const root = await write('/api/v1/projects/' + project.id + '/components', { name: names[0], reason: '验收' })
      for (const name of names.slice(1)) {
        const child = await write('/api/v1/projects/' + project.id + '/components', { name, parentComponentId: root.id, owner: '研发工程组', model: 'CTRL-' + (index + 1), notes: '联调验证组件', reason: '验收' })
        components.push(child)
        released.push(await write('/api/v1/components/' + child.id + '/versions', { versionNumber: '3.' + (index + 1) + '.17', maturity: 'Released', reason: '已完成验证' }))
      }
    }
    const baseline = await write('/api/v1/projects/' + project.id + '/baselines', { seriesCode: 'PILOT', baselineCode: '2026.09.13', publishImmediately: true, reason: '固定验收基线' })
    await write('/api/v1/projects/' + project.id + '/standard', { configurationBaselineId: baseline.id, reason: '显式设置标准' })
    for (const i of [0, 2, 3, 4, 6, 7]) testing.push(await write('/api/v1/components/' + components[i].id + '/versions', { versionNumber: '3.' + (i + 1) + '.20-rc.2', maturity: 'Testing', reason: '稳定性与联动测试' }))
    await write('/api/v1/component-versions/' + released[0].id + '/patches', { patchCode: 'HF.02', title: '修复异常重连后的通信超时', issueDescription: '网络恢复后偶发等待超时', resolutionDescription: '补充重试状态清理', status: 'Released' })
    await write('/api/v1/component-versions/' + released[1].id + '/safety', { state: 'Blocked', reason: '风险视觉语义验收' })
    const machines = []
    for (let i = 0; i < 4; i++) {
      const machine = await write('/api/v1/machines', { projectId: project.id, name: ['工艺验证机 A01', '联调验证机 A02', '产线设备 B01', '产线设备 B02'][i], serialNumber: token + '-' + i, machineType: 'Cluster 300', location: i < 2 ? '研发中心 · 一层实验室' : '生产车间 · A 区', owner: ['张工', '李工', '王工', '陈工'][i], stage: i < 2 ? 'T2' : 'HVM', chambers: [1, 2, 6].map(number => ({ number, stage: 'T1' })), reason: '验收' })
      machines.push(machine)
      await write('/api/v1/machines/' + machine.id + '/target', { configurationBaselineId: baseline.id, reason: '显式指派目标' })
      await write('/api/v1/machines/' + machine.id + '/facts', { operationType: 'InitialSnapshot', coverage: 'Full', sourceType: 'manual-ui', reason: '当前实际快照', items: components.map((component, n) => ({ componentId: component.id, versionId: released[n].id, absent: false, knownInstalledAt: null })) })
    }
    const frozen = await get('/api/v1/baselines/' + baseline.id)
    const facts = await get('/api/v1/machines/' + machines[0].id + '/facts')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await page.reload()
    await page.locator('.project-switch').getByText('先进工艺平台 · 软件配置管理', { exact: true }).waitFor()
    await capture('overview')
    await page.locator('.topbar').getByRole('button', { name: '新建项目', exact: true }).click()
    await page.getByRole('dialog').waitFor()
    await capture('create-project')
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.locator('.project-switch').click()
    await page.getByRole('dialog').waitFor()
    await capture('switch-project', 390)
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await nav('版本')
    await page.locator('.workspace-layout.inspector-collapsed').waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('.baseline-version')].some(element => element.textContent === '3.1.17'))
    await capture('project')
    await page.locator('.tree-node').first().click()
    await page.getByRole('button', { name: '登记新版本', exact: true }).waitFor()
    const entryButton = await page.getByRole('button', { name: '登记新版本', exact: true }).boundingBox()
    assert(entryButton.width >= 100 && entryButton.height <= 42, 'Version entry command must not wrap vertically')
    await capture('project-inspector')
    await page.locator('.baseline-tree .patch-open').first().hover()
    await page.locator('.patch-hover-content:visible').waitFor()
    await capture('patch-preview')
    await page.getByRole('button', { name: '收起补丁预览', exact: true }).click()
    await page.getByRole('button', { name: '测试历史', exact: true }).click()
    await page.locator('.laboratory-history-list article').first().waitFor()
    await capture('laboratory-history')
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await nav('基线')
    await page.locator('.baseline-timeline .timeline-item').first().click()
    await page.locator('.snapshot-root-column').first().waitFor()
    await page.locator('.project-baseline-history').scrollIntoViewIfNeeded()
    await capture('baseline-history')
    await nav('版本')
    for (const width of [1366, 768, 390]) await capture('project-responsive', width)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: '收起导航', exact: true }).click()
    assert.equal(await page.locator('.rail-collapsed .nav-item .anticon').count(), 9)
    await capture('navigation-collapsed')
    await page.getByRole('button', { name: '展开导航', exact: true }).click()
    await nav('机台')
    await page.locator('.machine-list-item').first().waitFor()
    assert.equal(await page.locator('.machine-detail-panel:visible').count(), 0)
    await capture('machines')
    await page.locator('.machine-list-item').first().click()
    await page.locator('.actual-node').first().waitFor()
    await capture('machine-configuration')
    await machineTab('阶段与腔室')
    await page.locator('.chamber-summary article').first().waitFor()
    await capture('machine-chambers')
    await machineTab('历史')
    await page.locator('.historical-configuration').waitFor()
    await capture('machine-history')
    await page.getByRole('button', { name: '新建机台 / 从已有机台复制资料' }).click()
    await page.getByRole('dialog').waitFor()
    await capture('create-machine')
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    for (const width of [768, 390]) await capture('machine-responsive', width)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await nav('配置比对')
    await page.getByLabel('左侧配置').selectOption(machines[0].id)
    await page.getByLabel('右侧配置').selectOption(baseline.id)
    await page.locator('.comparison-table tbody tr').first().waitFor()
    assert((await page.locator('.compare-summary').innerText()).includes('版本匹配：匹配'))
    assert((await page.locator('.compare-summary').innerText()).includes('风险：严重'))
    await capture('compare')
    await capture('compare', 390)
    await page.setViewportSize({ width: 1440, height: 1000 })
    for (const [name, file] of [['搜索', 'search'], ['版本导入', 'import'], ['部署记录', 'deployment'], ['用户与角色', 'users']]) {
      await nav(name)
      if (name === '搜索') {
        await page.getByLabel('搜索词').fill('3.1')
        await page.locator('.catalog-list .component-row').first().waitFor()
        await page.locator('.catalog-list .component-row').filter({ hasText: '设备控制服务' }).first().waitFor()
      }
      if (name === '部署记录') {
        await page.getByLabel('机台', { exact: true }).selectOption(machines[0].id)
        await page.locator('.component-list .component-row').first().waitFor()
      }
      if (name === '用户与角色') {
        await page.getByRole('button', { name: '新增用户', exact: true }).click()
        await page.getByRole('dialog').waitFor()
        await capture('create-user')
        await page.getByRole('dialog').getByLabel('用户名', { exact: true }).fill(viewerName)
        await page.getByRole('dialog').getByLabel('显示名').fill('只读视觉验收')
        await page.getByRole('dialog').getByLabel('初始密码').fill(viewerPassword)
        await page.getByRole('dialog').getByLabel('创建原因').fill('用户弹窗真实保存验收')
        await page.getByRole('dialog').getByRole('button', { name: '创建用户', exact: true }).click()
        await page.getByRole('dialog').waitFor({ state: 'hidden' })
        await page.getByRole('status').filter({ hasText: '用户已创建' }).waitFor()
        const account = (await get('/api/v1/admin/users')).find(user => user.userName === viewerName)
        assert(account, 'User created through the UI')
        await page.getByRole('button', { name: '调整角色', exact: true }).click()
        await page.getByRole('dialog').getByLabel('用户', { exact: true }).selectOption(account.id)
        await page.getByRole('dialog').getByLabel('新角色').selectOption('Engineer')
        await page.getByRole('dialog').getByLabel('变更原因').fill('角色弹窗真实保存验收')
        await page.getByRole('dialog').getByRole('button', { name: '变更角色', exact: true }).click()
        await page.getByRole('dialog').waitFor({ state: 'hidden' })
        assert((await get('/api/v1/admin/users')).find(user => user.id === account.id).roles.includes('Engineer'))
        await page.getByRole('button', { name: '调整角色', exact: true }).click()
        await page.getByRole('dialog').getByLabel('新角色').selectOption('Viewer')
        await page.getByRole('dialog').getByLabel('变更原因').fill('恢复只读角色验收')
        await capture('change-role')
        await page.getByRole('dialog').getByRole('button', { name: '变更角色', exact: true }).click()
        await page.getByRole('dialog').waitFor({ state: 'hidden' })
        await page.getByRole('button', { name: '新增用户', exact: true }).click()
        await page.getByRole('dialog').waitFor()
        await page.keyboard.press('Escape')
        await page.getByRole('dialog').waitFor({ state: 'hidden' })
        await page.getByLabel('筛选用户').fill('admin')
        assert.equal(await page.locator('.users-workspace form:visible').count(), 0)
      }
      await capture(file)
      await capture(file, 390)
      await page.setViewportSize({ width: 1440, height: 1000 })
    }
    await nav('运行总览')
    await page.locator('.overview-operations > summary').click()
    await page.locator('.overview-operations-content').waitFor()
    await capture('operations')
    await capture('operations', 390)
    const viewer = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
    assert((await viewer.request.post('/api/v1/auth/login', { data: { userName: viewerName, password: viewerPassword } })).ok())
    const viewerPage = await viewer.newPage()
    await viewerPage.goto('/')
    await viewerPage.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await viewerPage.reload()
    await viewerPage.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '版本', exact: true }).click()
    await viewerPage.locator('.tree-node').first().click()
    assert.equal(await viewerPage.locator('.component-inspector form:visible').count(), 0)
    assert.equal(await viewerPage.getByRole('button', { name: '新建项目', exact: true }).count(), 0)
    assert.equal(await viewerPage.getByRole('button', { name: '用户与角色', exact: true }).count(), 0)
    await capture('viewer', 1440, viewerPage)
    await viewer.close()
    assert.deepEqual(await get('/api/v1/baselines/' + baseline.id), frozen, 'UI viewing must preserve frozen baseline')
    assert.deepEqual(await get('/api/v1/machines/' + machines[0].id + '/facts'), facts, 'UI viewing must preserve facts')
    assert.deepEqual(errors, [])
    writeFileSync(path.join(output, 'result.json'), JSON.stringify({ passed: true, screenshots, scope: 'Visual evidence requires manual image review in addition to these assertions.' }, null, 2))
    console.log('Future UI passed: real login, 9 pages, responsive layouts, keyboard modal dismissal, readable entry commands, Viewer, frozen data, Match/Risk separation. Screenshots: ' + screenshots.length)
  } finally {
    if (project) await write('/api/v1/projects/' + project.id + '/archive', { reason: 'UI 验收结束' })
    await browser.close()
  }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1 })
