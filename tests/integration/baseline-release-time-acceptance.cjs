const { chromium } = require('playwright')
const { readFileSync } = require('node:fs')
const { execFileSync } = require('node:child_process')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL })
  const call = (url, data, key = randomUUID(), client = context.request) => client.post(url, { data, headers: { 'Idempotency-Key': key } })
  const write = async (url, data, key) => { const response = await call(url, data, key); assert(response.ok(), `${url}: ${await response.text()}`); return response.status() === 204 ? null : response.json() }
  const get = async url => { const response = await context.request.get(url); assert(response.ok(), await response.text()); return response.json() }
  const fixture = (baselineId, ...args) => execFileSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', path.resolve('tests/integration/baseline-metadata-fixture.ps1'), '-BaselineId', baselineId, ...args], { windowsHide: true })
  const reason = '基线发布时间语义自动验收'
  let project
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const token = randomUUID().slice(0, 8)
    project = await write('/api/v1/projects', { code: `BASELINE-FILTER-TIME-${token}`, name: '基线发布时间验收', reason })
    const component = await write(`/api/v1/projects/${project.id}/components`, { name: '控制软件', reason })
    await write(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V1', maturity: 'Released', reason })
    const baseline = async (code, publishImmediately = true) => write(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'TIME', baselineCode: code, publishImmediately, reason })
    const maintain = (id, data, key) => call(`/api/v1/baselines/${id}/maintenance`, { maintenanceMode: true, reason, ...data }, key)
    const impact = id => get(`/api/v1/baselines/${id}/operation-impact`)
    const recent = await baseline('近期发布')
    const before = await get(`/api/v1/baselines/${recent.id}`)
    const beforeImpact = await impact(recent.id)
    assert(beforeImpact.canWithdraw)
    const auditBefore = await get(`/api/v1/audit?entityId=${recent.id}`)
    const key = randomUUID()
    for (let i = 0; i < 2; i++) assert.equal((await maintain(recent.id, { releasedAt: '2020-02-03T08:30:45.123+08:00' }, key)).status(), 200)
    const after = await get(`/api/v1/baselines/${recent.id}`)
    assert.equal(new Date(after.baseline.releasedAt).toISOString(), '2020-02-03T00:30:45.123Z')
    assert.equal(after.baseline.createdAt, before.baseline.createdAt)
    assert.equal(after.baseline.releaseRecordedAt, before.baseline.releaseRecordedAt)
    assert.equal(after.baseline.releasedBy, before.baseline.releasedBy)
    assert.deepEqual(after.items, before.items)
    const afterImpact = await impact(recent.id)
    assert.equal(afterImpact.withdrawUntil, beforeImpact.withdrawUntil)
    assert(afterImpact.canWithdraw, 'Backdating business release time must not prematurely close the real action window')
    const auditAfter = await get(`/api/v1/audit?entityId=${recent.id}`)
    assert.deepEqual(auditAfter.filter(item => item.action !== 'HistoricalBaselineMaintained'), auditBefore)
    const maintenanceAudits = auditAfter.filter(item => item.action === 'HistoricalBaselineMaintained')
    assert.equal(maintenanceAudits.length, 1, 'Idempotent maintenance writes only one audit')
    assert(new Date(maintenanceAudits[0].occurredAt) >= new Date(before.baseline.createdAt))
    for (const invalid of [{ createdAt: '2020-01-01T00:00:00Z' }, { releasedAt: '1999-01-01T00:00:00Z' }, { releasedAt: '2100-01-01T00:00:00Z' }]) assert.equal((await maintain(recent.id, invalid)).status(), 400)
    assert.equal((await maintain(recent.id, { releasedAt: '2021-01-01T00:00:00Z' }, key)).status(), 409)
    const draft = await baseline('尚未发布', false)
    assert.equal((await maintain(draft.id, { releasedAt: '2020-01-01T00:00:00Z' })).status(), 400)
    assert.equal((await get(`/api/v1/baselines/${draft.id}`)).baseline.releasedAt, null)

    const userName = `baseline-time-admin-${token}`, password = randomUUID()
    await write('/api/v1/admin/users', { userName, password, displayName: '普通管理员', role: 'Admin', reason })
    const ordinaryAdmin = await browser.newContext({ baseURL })
    const login = await ordinaryAdmin.request.post('/api/v1/auth/login', { data: { userName, password } })
    assert(login.ok())
    assert.equal((await call(`/api/v1/baselines/${recent.id}/maintenance`, { maintenanceMode: true, releasedAt: '2020-01-01T00:00:00Z', reason }, randomUUID(), ordinaryAdmin.request)).status(), 403)

    assert.equal((await call(`/api/v1/baselines/${recent.id}/withdraw-release`, { reason })).status(), 200, 'Database trigger must use the same release action window as the API')
    const old = await baseline('过期发布')
    fixture(old.id, '-ReleaseRecordedAt', '2020-01-01T00:00:00Z')
    assert.equal((await maintain(old.id, { releasedAt: new Date(Date.now() - 1000).toISOString() })).status(), 200)
    assert.equal((await impact(old.id)).canWithdraw, false, 'Correcting publication to today must not reopen the expired withdrawal window')
    assert.equal((await call(`/api/v1/baselines/${old.id}/withdraw-release`, { reason })).status(), 409)
    fixture(old.id, '-VerifyWithdrawalGuard')
    const missing = await baseline('缺少操作历史的旧数据')
    fixture(missing.id, '-RemoveReleaseRecord')
    const missingImpact = await impact(missing.id)
    assert.equal(missingImpact.canWithdraw, false)
    assert.equal(missingImpact.withdrawUntil, null, 'Missing immutable release action must never fall back to editable ReleasedAt')
    assert.equal((await call(`/api/v1/baselines/${missing.id}/withdraw-release`, { reason })).status(), 409)
    fixture(missing.id, '-VerifyWithdrawalGuard')
    console.log('Baseline release time acceptance passed: historical publish date, preserved recording/audit/action timestamps, precision, idempotency, permissions, draft/future/legacy rejection, and API/database withdrawal windows including missing history.')
  } finally {
    if (project) await call(`/api/v1/projects/${project.id}/archive`, { reason: '验收完成归档' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
