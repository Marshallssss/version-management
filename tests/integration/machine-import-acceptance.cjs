const { chromium } = require('playwright')
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs')
const { execFileSync } = require('node:child_process')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5080', viewport: { width: 1440, height: 1000 } })
  const api = context.request, token = randomUUID().slice(0, 8), projects = []
  const output = path.resolve('artifacts/machine-import'); mkdirSync(output, { recursive: true })
  const workbook = path.join(output, 'machine-template.xlsx')
  const call = (url, data, method = 'POST', client = api, key = randomUUID()) => client.fetch(url, { method, data, headers: { 'Idempotency-Key': key } })
  const write = async (url, data, method = 'POST') => { const r = await call(url, data, method); assert(r.ok(), `${url}: ${await r.text()}`); return r.status() === 204 ? null : r.json() }
  const get = async url => { const r = await api.get(url); assert(r.ok(), await r.text()); return r.json() }
  let page
  try {
    await write('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    for (let i = 0; i < 2; i++) projects.push((await write('/api/v1/projects', { code: `MACHINE-EXCEL-${token}-${i}`, name: `机台导入验收 ${i}`, reason: '验收' })).id)
    const [projectId, other] = projects, route = `/api/v1/projects/${projectId}/machine-import`
    const component = await write(`/api/v1/projects/${projectId}/components`, { name: '控制器', reason: '验收' })
    const version = await write(`/api/v1/components/${component.id}/versions`, { versionNumber: '001.02', maturity: 'Released', reason: '验收' })
    await write(`/api/v1/projects/${projectId}/baselines`, { seriesCode: 'XLSX', baselineCode: '机台基线一', publishImmediately: true, reason: '验收' })
    const download = await api.get(`${route}/template`); assert(download.ok())
    const original = await download.body()
    const fixture = changes => {
      writeFileSync(workbook, original)
      return JSON.parse(execFileSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', path.resolve('tests/integration/matrix-workbook-fixture.ps1'), '-Path', workbook, '-CellsJson', JSON.stringify(changes)], { encoding: 'utf8', windowsHide: true }).replace(/^\uFEFF/, ''))
    }
    const cells = fixture({})
    assert.equal(cells.A1, `ConfigHub.Machines.v1:${projectId}`)
    assert.equal(cells.__layout.freeze, 'C6')
    assert.match(cells.Q3, /YYYY-MM-DD/)
    const good = { A6: `EXCEL-${token}-A`, B6: '实验室机台', C6: '机型A', D6: '实验室', E6: '张工', F6: '刻蚀', G6: '六腔室', H6: '在用', J6: 'Lab', K6: 'Lab', P6: 'T1', Q6: '机台基线一', R6: '2026-09-19', S6: '已核对设备台账', A7: `EXCEL-${token}-B`, B7: '未知基线机台', H7: '短期 CIP', I7: '2026-12-01 09:00', J7: 'T1', Q7: '不存在的基线', S7: '仅录入机台资料', A8: `EXCEL-${token}-C`, B8: '无版本机台', S8: '新设备' }
    const upload = () => ({ fileName: '机台登记.xlsx', contentBase64: readFileSync(workbook).toString('base64'), reason: '批量资料验收' })
    fixture(good)
    assert.equal((await call(`/api/v1/projects/${other}/machine-import/preview`, upload())).status(), 400)
    for (const changes of [{ A5: '被修改表头' }, { A1: '错误项目' }, { A6: { formula: '1+1' } }, { T6: '越界内容' }, { R6: { numeric: 46283 } }]) {
      fixture({ ...good, ...changes }); assert.equal((await call(`${route}/preview`, upload())).status(), 400)
    }
    fixture({ ...good, A7: good.A6, B8: '', J8: '坏阶段' })
    const invalid = await write(`${route}/preview`, upload())
    const rejected = await get(`${route}/batches/${invalid.id}`)
    assert(rejected.rows.every(row => row.validationError))
    assert.equal((await call(`${route}/batches/${invalid.id}/commit`, {})).status(), 409)
    assert(!(await get('/api/v1/machines')).some(machine => machine.projectId === projectId))
    fixture(good)
    const key = randomUUID(), staged1 = await call(`${route}/preview`, upload(), 'POST', api, key), staged = await staged1.json()
    assert(staged1.ok(), JSON.stringify(staged))
    assert.equal((await (await call(`${route}/preview`, upload(), 'POST', api, key)).json()).id, staged.id)
    const preview = await get(`${route}/batches/${staged.id}`)
    assert.equal(preview.status, 'Validated'); assert.equal(preview.rows.filter(row => row.data.warning).length, 1)
    assert.equal((await call(`/api/v1/imports/${staged.id}/commit`, {})).status(), 409)
    assert.equal((await api.get(`/api/v1/projects/${other}/machine-import/batches/${staged.id}`)).status(), 404)
    fixture({ A6: `RETRY-${token}-A`, B6: '先成功机台', S6: '重试验收', A7: `RETRY-${token}-B`, B7: '后成功机台', S7: '重试验收' })
    const retryBatch = await write(`${route}/preview`, upload())
    const racingMachine = await write('/api/v1/machines', { projectId, serialNumber: `RETRY-${token}-B`, name: '并发登记', reason: '验收' })
    await write(`${route}/batches/${retryBatch.id}/commit`, {})
    const partial = await get(`${route}/batches/${retryBatch.id}`)
    assert.equal(partial.status, 'Failed'); assert.equal(partial.rows.filter(row => row.data.completed).length, 1)
    assert.match(partial.rows[1].data.error, /已存在/)
    await write(`/api/v1/machines/${racingMachine.id}`, { serialNumber: `RETRY-${token}-RENAMED`, name: '并发登记', status: 'Active', reason: '释放验收序列号' }, 'PUT')
    await Promise.all([write(`${route}/batches/${retryBatch.id}/commit`, {}), write(`${route}/batches/${retryBatch.id}/commit`, {})])
    const retried = await get(`${route}/batches/${retryBatch.id}`)
    assert.equal(retried.status, 'Committed'); assert.equal(retried.rows[0].data.machineId, partial.rows[0].data.machineId)
    assert.equal((await get(`/api/v1/audit?entityId=${partial.rows[0].data.machineId}`)).filter(item => item.action === 'MachineCreated').length, 1)
    const withdrawn = await write(`/api/v1/projects/${projectId}/baselines`, { seriesCode: 'XLSX-SECOND', baselineCode: '即将撤回的基线', publishImmediately: true, reason: '过期预览验收' })
    fixture({ A6: `STALE-${token}`, B6: '过期预览机台', Q6: '即将撤回的基线', R6: '2026-09-19', S6: '过期预览验收' })
    const stale = await write(`${route}/preview`, upload())
    await write(`/api/v1/baselines/${withdrawn.id}/withdraw-release`, { reason: '过期预览验收' })
    await write(`${route}/batches/${stale.id}/commit`, {})
    const staleResult = await get(`${route}/batches/${stale.id}`)
    assert.equal(staleResult.status, 'Committed'); assert.match(staleResult.rows[0].data.warning, /撤回/)
    assert.equal((await get(`/api/v1/machines/${staleResult.rows[0].data.machineId}/configuration`)).length, 0)
    fixture(good)
    for (const role of ['Viewer', 'Engineer']) {
      const userName = `machine-excel-${role}-${token}`, password = randomUUID()
      await write('/api/v1/admin/users', { userName, displayName: '权限验收', password, role, reason: '验收' })
      const limited = await browser.newContext({ baseURL: 'http://127.0.0.1:5080' })
      assert((await call('/api/v1/auth/login', { userName, password }, 'POST', limited.request)).ok())
      assert.equal((await limited.request.get(`${route}/template`)).status(), 403)
      assert.equal((await call(`${route}/batches/${staged.id}/commit`, {}, 'POST', limited.request)).status(), 403)
      await limited.close()
    }
    page = await context.newPage()
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), projectId); await page.reload()
    await page.locator('.nav-item').filter({ hasText: /^版本导入$/ }).click()
    await page.getByRole('list', { name: '版本导入步骤' }).waitFor()
    await page.screenshot({ path: path.join(output, 'version-guidance.png'), fullPage: true })
    await page.locator('.nav-item').filter({ hasText: /^机台$/ }).click()
    await page.getByRole('button', { name: 'Excel 导入机台', exact: true }).click()
    await page.getByRole('list', { name: '机台导入步骤' }).waitFor()
    await page.getByLabel('填写后的机台 Excel', { exact: true }).setInputFiles(workbook)
    await page.getByLabel('机台导入原因', { exact: true }).fill('界面预览确认')
    await page.getByRole('button', { name: '检查文件并预览', exact: true }).click()
    await page.getByRole('button', { name: '确认导入机台', exact: true }).waitFor()
    await page.getByText('可导入，版本留空', { exact: true }).waitFor()
    await page.getByRole('button', { name: '确认导入机台', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '导入已完成' }).waitFor()
    const batchList = await get(`${route}/batches`), completedBatch = batchList.find(item => item.status === 'Committed')
    assert(completedBatch)
    const results = await get(`${route}/batches/${completedBatch.id}`)
    assert.equal(results.rows.length, 3); assert(results.rows.every(row => row.data.completed))
    const [a, b, c] = results.rows.map(row => row.data.machineId)
    const machines = await get('/api/v1/machines'), machine = machines.find(m => m.id === a)
    assert.equal(machine.process, '刻蚀'); assert.equal(machine.equipmentConfiguration, '六腔室'); assert.equal(machine.owner, '张工'); assert.deepEqual(machine.chambers, [1, 6])
    assert.equal(machines.find(m => m.id === b).status, 'ShortTermCip')
    const actual = await get(`/api/v1/machines/${a}/configuration`)
    assert.equal(actual[0].versionId, version.id); assert.equal(actual[0].knownInstalledAt, null)
    assert.equal((await get(`/api/v1/machines/${b}/configuration`)).length, 0)
    assert.equal((await get(`/api/v1/machines/${c}/configuration`)).length, 0)
    assert.equal(await (await api.get(`/api/v1/machines/${a}/target`)).text(), '')
    await write(`${route}/batches/${completedBatch.id}/commit`, {})
    assert.equal((await get(`/api/v1/machines/${a}/facts`)).length, 1)
    const again = await write(`${route}/preview`, upload())
    assert((await get(`${route}/batches/${again.id}`)).rows.every(row => /已存在/.test(row.validationError)))
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
      await page.screenshot({ path: path.join(output, `machines-${width}.png`), fullPage: true, animations: 'disabled' })
    }
    assert.deepEqual(errors, [])
    console.log('Machine Excel passed: project/header/formula/range guards, preview without writes, duplicate/CIP/stage validation, baseline warning allows metadata-only import, initial snapshot without installed time or target, permissions, durable history/idempotency, multi-row UI and responsive guidance.')
  } catch (error) { if (page) await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {}); throw error }
  finally { for (const id of projects) await write(`/api/v1/projects/${id}/archive`, { reason: '验收结束' }).catch(() => {}); await browser.close() }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1 })
