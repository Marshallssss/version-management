const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const call = async (url, data, status = 200, method = 'post', key = randomUUID(), client = context.request) => {
    const response = await client[method](url, { data, headers: { 'Idempotency-Key': key } })
    assert.equal(response.status(), status, url + ': ' + await response.text())
    return response.status() === 204 || !(await response.text()) ? null : response.json()
  }
  let project
  try {
    await call('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password }, 204)
    project = await call('/api/v1/projects', { code: 'RECORD-' + randomUUID().slice(0, 8), name: '记录维护验收项目', description: '项目简介现在与当前项目名称一起显示，不再占据独立的大标题区。', reason: '自动化验收' }, 201)
    const root = await call(`/api/v1/projects/${project.id}/components`, { name: '控制系统', reason: '自动化验收' }, 201)
    const root2 = await call(`/api/v1/projects/${project.id}/components`, { name: '视觉系统', reason: '自动化验收' }, 201)
    const child = await call(`/api/v1/projects/${project.id}/components`, { name: '控制程序', parentComponentId: root.id, reason: '自动化验收' }, 201)
    const labChild = await call(`/api/v1/projects/${project.id}/components`, { name: '视觉驱动', parentComponentId: root2.id, reason: '自动化验收' }, 201)
    const version = await call(`/api/v1/components/${child.id}/versions`, { versionNumber: 'V1', maturity: 'Released', reason: '自动化验收' }, 201)
    await call(`/api/v1/components/${labChild.id}/versions`, { versionNumber: 'V1', maturity: 'Released', reason: '自动化验收' }, 201)
    const testing = await call(`/api/v1/components/${labChild.id}/versions`, { versionNumber: 'V2-test', maturity: 'Testing', reason: '自动化验收' }, 201)
    const baseline = await call(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'S', baselineCode: 'HISTORY-V1', reason: '自动化验收' }, 201)
    await call(`/api/v1/baselines/${baseline.id}/review`, { reason: '冻结快照验收' }, 201)
    await call(`/api/v1/baselines/${baseline.id}/review/approve`, { reason: '冻结快照验收' })
    await call(`/api/v1/baselines/${baseline.id}/release`, { reason: '冻结快照验收' })
    const snapshotBefore = await (await context.request.get(`/api/v1/baselines/${baseline.id}`)).json()
    const patch = await call(`/api/v1/component-versions/${testing.id}/patches`, { patchCode: 'HF-1', title: '改善启动稳定性', issueDescription: '启动异常', resolutionDescription: '修正初始化顺序', status: 'Released' }, 201)
    const draft = await call(`/api/v1/component-versions/${testing.id}/patches`, { patchCode: 'HF-2', title: '误录草稿', issueDescription: '误录', resolutionDescription: '待处理', status: 'Draft' }, 201)
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: '项目' }).click()
    await page.locator('.project-intro').waitFor()
    assert.equal(await page.locator('.workspace-heading').count(), 0)
    assert((await page.locator('.project-switch').innerText()).includes(project.name || '记录维护验收项目'))
    await page.locator('.laboratory-tree .patch-open').waitFor()
    await page.locator('.laboratory-tree .patch-open').hover()
    await page.locator('.patch-hover-content').filter({ hasText: '改善启动稳定性' }).waitFor()
    await page.locator('.laboratory-tree .patch-open').click()
    await page.locator('.patch-location-guide').waitFor()
    assert((await page.locator('.patch-list').innerText()).includes('改善启动稳定性'))
    const output = path.resolve('artifacts/record-maintenance')
    mkdirSync(output, { recursive: true })
    await page.screenshot({ path: path.join(output, 'patch-navigation.png'), fullPage: true })
    await page.locator('.patch-location-guide').waitFor({ state: 'detached', timeout: 7000 })
    await page.getByRole('button', { name: '调测维护', exact: true }).click()
    const maintenanceForm = page.locator('.version-maintenance form')
    await maintenanceForm.getByLabel('版本号', { exact: true }).fill('V2-test-edited')
    await maintenanceForm.getByLabel('维护原因').fill('界面维护保存验收')
    await maintenanceForm.getByRole('button', { name: '保存调测修改' }).click()
    await maintenanceForm.waitFor({ state: 'detached' })
    await page.locator('.laboratory-tree').getByText('V2-test-edited', { exact: true }).waitFor()
    await page.locator('.baseline-timeline button').filter({ hasText: 'HISTORY-V1' }).click()
    await page.locator('.snapshot-root-column').first().waitFor()
    assert.equal(await page.locator('.snapshot-root-column').count(), 2)
    assert.equal(await page.locator('.snapshot-root-column').first().locator('.snapshot-child-branch').count(), 1)
    await page.locator('.baseline-snapshot').screenshot({ path: path.join(output, 'baseline-hierarchy.png') })
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile layout overflow')
    await page.screenshot({ path: path.join(output, 'project-mobile.png'), fullPage: true })

    const reason = { reason: '自动化撤回验证' }
    await call(`/api/v1/version-patches/${patch.id}/manage`, { ...reason, action: 'delete' }, 409)
    const withdrawKey = randomUUID()
    await call(`/api/v1/version-patches/${patch.id}/manage`, { ...reason, action: 'withdraw' }, 200, 'post', withdrawKey)
    await call(`/api/v1/version-patches/${patch.id}/manage`, { ...reason, action: 'withdraw' }, 200, 'post', withdrawKey)
    await call(`/api/v1/version-patches/${patch.id}/manage`, { reason: '不同原因', action: 'withdraw' }, 409, 'post', withdrawKey)
    const deleteKey = randomUUID()
    await call(`/api/v1/version-patches/${draft.id}/manage`, { ...reason, action: 'delete' }, 200, 'post', deleteKey)
    await call(`/api/v1/version-patches/${draft.id}/manage`, { ...reason, action: 'delete' }, 200, 'post', deleteKey)
    const detail = await (await context.request.get(`/api/v1/component-versions/${testing.id}`)).json()
    assert.equal(detail.patches.length, 1)
    assert.equal(detail.patches[0].status, 'Withdrawn')
    assert.equal(detail.patches[0].title, '改善启动稳定性')
    const maintenance = { versionNumber: 'V1-corrected', maturity: 'Released', createdAt: '2001-01-01T00:00:00Z', releasedAt: '2002-01-01T00:00:00Z', reason: '修正历史测试登记', maintenanceMode: true }
    const maintainKey = randomUUID()
    await call(`/api/v1/component-versions/${version.id}/maintenance`, maintenance, 200, 'post', maintainKey)
    await call(`/api/v1/component-versions/${version.id}/maintenance`, maintenance, 200, 'post', maintainKey)
    const maintained = await (await context.request.get(`/api/v1/component-versions/${version.id}`)).json()
    assert.equal(maintained.version.versionNumber, 'V1-corrected')
    assert(maintained.transitions.some(item => item.toState === 'Released' && item.occurredAt.startsWith('2002-01-01')))
    const snapshotAfter = await (await context.request.get(`/api/v1/baselines/${baseline.id}`)).json()
    assert.deepEqual(snapshotAfter.items, snapshotBefore.items)
    await call(`/api/v1/component-versions/${version.id}/maintenance`, { ...maintenance, maturity: '999' }, 400)
    if (process.env.CONFIGHUB_CLOSED_MAINTENANCE_URL) {
      const closed = await browser.newContext({ baseURL: process.env.CONFIGHUB_CLOSED_MAINTENANCE_URL })
      await call('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password }, 204, 'post', randomUUID(), closed.request)
      assert.equal((await (await closed.request.get('/api/v1/maintenance-capabilities')).json()).enabled, false)
      await call(`/api/v1/component-versions/${version.id}/maintenance`, maintenance, 409, 'post', randomUUID(), closed.request)
      await call(`/api/v1/baselines/${baseline.id}/maintenance`, { reason: '关闭开关验收', maintenanceMode: true }, 409, 'post', randomUUID(), closed.request)
      await closed.close()
    }
    const memberName = 'record-engineer-' + randomUUID().slice(0, 8)
    const password = randomUUID()
    const member = await call('/api/v1/admin/users', { userName: memberName, displayName: '验收工程师', password, role: 'Engineer', reason: '权限验收' }, 201)
    await call(`/api/v1/projects/${project.id}/members`, { userId: member.id, role: 'Engineer', reason: '权限验收' })
    const memberContext = await browser.newContext({ baseURL })
    await call('/api/v1/auth/login', { userName: memberName, password }, 204, 'post', randomUUID(), memberContext.request)
    await call(`/api/v1/component-versions/${version.id}/maintenance`, maintenance, 403, 'post', randomUUID(), memberContext.request)
    await call(`/api/v1/version-patches/${patch.id}/manage`, { ...reason, action: 'delete' }, 403, 'post', randomUUID(), memberContext.request)
    await memberContext.close()
    const machine = await call('/api/v1/machines', { projectId: project.id, serialNumber: 'CIP-' + randomUUID().slice(0, 8), name: 'CIP 验收机台', reason: '状态验收' }, 201)
    const machineInput = { serialNumber: 'CIP-' + machine.id, name: 'CIP 验收机台', status: 'ShortTermCip', reason: '状态验收' }
    await call(`/api/v1/machines/${machine.id}`, machineInput, 400, 'put')
    for (const status of ['ShortTermCip', 'LongTermCip', 'NoProduction', 'Active']) {
      await call(`/api/v1/machines/${machine.id}`, { ...machineInput, status, expectedResumeAt: '2030-01-01T00:00:00Z' }, 200, 'put')
      const machines = await (await context.request.get('/api/v1/machines')).json()
      const saved = machines.find(item => item.id === machine.id)
      assert.equal(saved.status, status)
      assert.equal(saved.expectedResumeAt !== null, status.endsWith('Cip'))
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: '机台' }).click()
    await page.locator('.machine-list-item').filter({ hasText: machineInput.serialNumber }).click()
    await page.getByRole('button', { name: '编辑机台资料', exact: true }).click()
    await page.locator('.machine-edit select').selectOption('ShortTermCip')
    await page.locator('.machine-edit').getByLabel('预计恢复时间').fill('2030-01-01T08:00')
    await page.locator('.machine-edit').getByLabel('修改原因').fill('CIP 界面保存验收')
    await page.locator('.machine-edit').getByRole('button', { name: '保存资料' }).click()
    await page.locator('.machine-edit').waitFor({ state: 'hidden' })
    await page.locator('.machine-detail-panel .machine-statuses').getByText(/短期 CIP/).waitFor()
    await page.locator('.machine-detail-panel').screenshot({ path: path.join(output, 'machine-cip.png') })
    assert.deepEqual(errors, [])
    console.log('Record maintenance acceptance passed: patch lifecycle/replay, SuperAdmin editing, snapshot preservation, CIP scheduling, desktop/mobile UX.')
  } catch (error) {
    mkdirSync(path.resolve('artifacts/record-maintenance'), { recursive: true })
    await page.screenshot({ path: path.resolve('artifacts/record-maintenance/failure.png'), fullPage: true })
    throw error
  } finally {
    if (project) await call(`/api/v1/projects/${project.id}/archive`, { reason: '验收结束归档' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
