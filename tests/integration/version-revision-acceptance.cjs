const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const assert = require('node:assert/strict')
async function main() {
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const ctx = await browser.newContext({ baseURL: 'http://127.0.0.1:5080' })
  const api = ctx.request, reason = '累计修订验收'
  const call = (url, data, key = randomUUID()) => api.post(url, { data, headers: { 'Idempotency-Key': key } })
  const post = async (url, data, key) => { const r = await call(url, data, key); assert(r.ok(), await r.text()); return r.status() === 204 ? null : r.json() }
  let project, machine
  try {
    await post('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    project = await post('/api/v1/projects', { code: 'REV-' + randomUUID().slice(0,8), name: reason, reason })
    const c = await post(`/api/v1/projects/${project.id}/components`, { name: '控制软件', reason })
    const v = await post(`/api/v1/components/${c.id}/versions`, { versionNumber: 'V1', historicalCreatedAt: '2020-01-01T00:00:00Z', reason })
    const patch = code => post(`/api/v1/component-versions/${v.id}/patches`, { patchCode: code, title: code, issueDescription: '问题', resolutionDescription: '冻结修复说明', status: 'Released' })
    const p1 = await patch('P1'), p2 = await patch('P2')
    const route = `/api/v1/component-versions/${v.id}/revisions`, key = randomUUID()
    const rev1 = await post(route, { patchIds: [p1.id], reason }, key)
    assert.equal(rev1.revisionNo, 1)
    assert.equal((await post(route, { patchIds: [p1.id], reason }, key)).id, rev1.id)
    let revisions = await (await api.get(route)).json()
    assert.deepEqual(revisions.map(x => x.revisionNo), [0,1]); assert.equal(revisions[0].patches.length, 0)
    const frozen = revisions[1]
    await post(`/api/v1/version-patches/${p1.id}/manage`, { action: 'withdraw', reason })
    const rev2 = await post(route, { patchIds: [p1.id,p2.id], reason })
    assert.equal(rev2.revisionNo, 2)
    revisions = await (await api.get(route)).json()
    assert.deepEqual(revisions[1], frozen)
    assert.equal(revisions[2].patches.length, 2)
    assert.equal((await call(route, { patchIds: [p2.id], reason })).status(), 409)
    assert.equal((await call(route, { patchIds: [p1.id,p2.id], reason })).status(), 409)
    machine = await post('/api/v1/machines', { projectId: project.id, serialNumber: randomUUID(), name: '修订验收机台', reason })
    const factsRoute = `/api/v1/machines/${machine.id}/facts`
    const fact = (revisionId, operationType, effectiveAt, knownInstalledAt = null) => ({ operationType, effectiveAt, coverage: 'Partial', sourceType: 'Manual', reason, items: [{ componentId: c.id, versionId: v.id, revisionId, absent: false, knownInstalledAt }] })
    const current = async () => (await (await api.get(`/api/v1/machines/${machine.id}/configuration`)).json())[0]
    await post(factsRoute, fact(null, 'InitialSnapshot', '2021-01-01T00:00:00Z'))
    assert.equal((await current()).revisionNo, null, 'Legacy unknown is not original or latest')
    await post(factsRoute, fact(revisions[0].id, 'Install', '2022-01-01T00:00:00Z', '2022-01-01T00:00:00Z'))
    assert.equal((await current()).revisionNo, 0)
    await post(factsRoute, fact(rev1.id, 'Observation', '2023-01-01T00:00:00Z'))
    assert.equal((await current()).revisionNo, 1)
    assert.equal((await current()).knownInstalledAt, null, 'Observation of changed revision cannot inherit old install time')
    const upgrade = fact(rev2.id, 'Upgrade', '2024-01-01T00:00:00Z', '2024-01-01T00:00:00Z'), upgradeKey = randomUUID()
    await post(factsRoute, upgrade, upgradeKey); await post(factsRoute, upgrade, upgradeKey)
    assert.equal((await current()).revisionNo, 2)
    assert.equal((await (await api.get(factsRoute)).json()).length, 4, 'Replay must not create a second upgrade')
    const old = await (await api.get(`/api/v1/machines/${machine.id}/configuration-at?at=2022-06-01T00:00:00Z`)).json()
    assert.equal(old.items[0].revisionNo, 0)
    const other = await post(`/api/v1/components/${c.id}/versions`, { versionNumber: 'V2', historicalCreatedAt: '2020-01-01T00:00:00Z', reason })
    const wrong = fact(rev1.id, 'Observation', '2025-01-01T00:00:00Z'); wrong.items[0].versionId = other.id
    assert.equal((await call(factsRoute, wrong)).status(), 400)
    assert.equal((await current()).revisionNo, 2)
    const page = await ctx.newPage()
    await page.goto('/'); await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id); await page.reload()
    await page.locator('.nav-item').filter({ hasText: /^版本$/ }).click(); await page.locator('.root-node').first().click()
    await page.getByRole('button', { name: '补丁', exact: true }).click()
    await page.getByRole('heading', { name: '累计补丁修订', exact: true }).waitFor()
    await page.getByText('修订 2 · 2 个补丁', { exact: true }).waitFor()
    await page.locator('.nav-item').filter({ hasText: /^机台$/ }).click()
    await page.getByRole('button', { name: /修订验收机台/ }).click()
    await page.locator('.actual-configuration-tree').waitFor()
    await page.locator('.actual-configuration-tree').getByText('V1 · 修订 2', { exact: true }).waitFor()
    await page.getByRole('button', { name: '记录局部观察', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('组件', { exact: true }).selectOption(c.id)
    await dialog.getByLabel('版本', { exact: true }).selectOption(v.id)
    await dialog.getByLabel('实际补丁修订', { exact: true }).selectOption(revisions[0].id)
    await dialog.getByLabel('观察原因', { exact: true }).fill(reason)
    mkdirSync('artifacts/version-revision', { recursive: true })
    await dialog.scrollIntoViewIfNeeded()
    await page.screenshot({ path: 'artifacts/version-revision/observation.png', animations: 'disabled' })
    await dialog.getByRole('button', { name: '记录局部观察', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal((await current()).revisionNo, 0)
    assert.equal((await current()).knownInstalledAt, null)
    await page.getByRole('button', { name: '录入完整配置', exact: true }).click()
    await page.getByText('打开完整配置工作台', { exact: true }).click()
    await page.getByRole('button', { name: '加载当前实际配置', exact: true }).click()
    assert.equal(await page.getByRole('dialog').getByLabel('实际补丁修订', { exact: true }).inputValue(), revisions[0].id)
    await page.getByRole('dialog').scrollIntoViewIfNeeded()
    await page.screenshot({ path: 'artifacts/version-revision/full-configuration.png', animations: 'disabled' })
    await page.getByRole('dialog').locator('.ant-modal-close').click()
    const baseline = revisionId => post(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'REV', baselineCode: 'BL-' + randomUUID().slice(0,8), reason, publishImmediately: true, versionSelections: [{ componentId: c.id, versionId: v.id, revisionId }] })
    const originalBaseline = await baseline(revisions[0].id), patchedBaseline = await baseline(rev2.id)
    const snapshot = await (await api.get(`/api/v1/baselines/${patchedBaseline.id}`)).json()
    assert.equal(snapshot.items[0].revisionId, rev2.id); assert.equal(snapshot.items[0].revisionNo, 2)
    let compared = await (await api.get(`/api/v1/machines/${machine.id}/compare-baseline/${patchedBaseline.id}`)).json()
    assert.equal(compared.items[0].status, 'Matched'); assert.equal(compared.items[0].revisionStatus, 'Mismatch')
    const baselineCompared = await (await api.get(`/api/v1/baselines/${originalBaseline.id}/compare/${patchedBaseline.id}`)).json()
    assert.equal(baselineCompared.items[0].revisionStatus, 'Mismatch')
    const badBaseline = await call(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'REV', baselineCode: 'BAD', reason, versionSelections: [{ componentId: c.id, versionId: other.id, revisionId: rev2.id }] })
    assert.equal(badBaseline.status(), 400)
    const upgradeAt = new Date(Date.now() + 1000).toISOString()
    const bulk = await post(`/api/v1/projects/${project.id}/bulk-baseline-upgrades`, { configurationBaselineId: patchedBaseline.id, machineIds: [machine.id], effectiveAt: upgradeAt, reason })
    assert.equal(bulk.succeeded, 1); assert.equal((await current()).revisionId, rev2.id)
    compared = await (await api.get(`/api/v1/machines/${machine.id}/compare-baseline/${patchedBaseline.id}`)).json()
    assert.equal(compared.items[0].revisionStatus, 'Matched')
    assert.equal((await (await api.get(`/api/v1/baselines/${originalBaseline.id}`)).json()).items[0].revisionNo, 0)
    await page.locator('.nav-item').filter({ hasText: /^基线$/ }).click()
    await page.getByText(snapshot.baseline.code, { exact: true }).first().click()
    await page.locator('.snapshot-tree').getByText('V1 · 修订 2', { exact: true }).waitFor()
    await page.screenshot({ path: 'artifacts/version-revision/baseline.png', animations: 'disabled' })
    await post(`/api/v1/component-versions/${v.id}/safety`, { state: 'Blocked', reason })
    assert.equal((await call(route, { patchIds: [], reason })).status(), 409)
    console.log('Version revision acceptance passed: original/cumulative snapshots, withdrawal isolation, duplicate prevention, replay, blocked state and real UI.')
  } finally { if (machine) await api.delete(`/api/v1/machines/${machine.id}`, { data: { reason }, headers: { 'Idempotency-Key': randomUUID() } }); if (project) await post(`/api/v1/projects/${project.id}/archive`, { reason }); await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode=1 })
