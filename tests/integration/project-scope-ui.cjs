const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')

async function main() {
  const baseURL = process.env.CONFIGHUB_TEST_URL || 'http://127.0.0.1:5080'
  const config = JSON.parse(readFileSync(path.join(process.env.LOCALAPPDATA, 'ConfigHub/appsettings.local.json'), 'utf8').replace(/^\uFEFF/, ''))
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const admin = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const output = path.resolve('artifacts/project-scope-ui')
  mkdirSync(output, { recursive: true })
  const projects = []
  const post = async (url, data, client = admin.request) => {
    const response = await client.post(url, { data, headers: { 'Idempotency-Key': randomUUID() } })
    assert(response.ok(), url + ': ' + await response.text())
    return response.status() === 204 ? null : response.json()
  }
  let page
  try {
    await post('/api/v1/auth/login', { email: config.ConfigHub.BootstrapAdmin.Email, password: config.ConfigHub.BootstrapAdmin.Password })
    const project = await post('/api/v1/projects', { code: 'SCOPE-' + randomUUID().slice(0, 8), name: '控制平台', description: '实验室与产线的软件配置管理，统一查看测试进展、项目基线与机台状态。', reason: '项目范围验收' })
    projects.push(project.id)
    const other = await post('/api/v1/projects', { code: 'OTHER-' + randomUUID().slice(0, 8), name: '其他项目', reason: '范围隔离验收' })
    projects.push(other.id)
    const roots = []
    const components = []
    const versions = []
    for (const name of ['主控系统', '视觉系统']) {
      const root = await post(`/api/v1/projects/${project.id}/components`, { name, reason: '验收' })
      roots.push(root)
      const component = await post(`/api/v1/projects/${project.id}/components`, { name: name + '程序', parentComponentId: root.id, reason: '验收' })
      components.push(component)
      versions.push(await post(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V1', maturity: 'Released', reason: '验收' }))
      await post(`/api/v1/components/${component.id}/versions`, { versionNumber: 'V2-test', maturity: 'Testing', reason: '测试验收' })
    }
    const baseline = await post(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'S', baselineCode: 'BL-1', reason: '验收' })
    await post(`/api/v1/baselines/${baseline.id}/review`, { reason: '验收' })
    await post(`/api/v1/baselines/${baseline.id}/review/approve`, { reason: '验收' })
    await post(`/api/v1/baselines/${baseline.id}/release`, { reason: '验收' })
    const draft = await post(`/api/v1/projects/${project.id}/baselines`, { seriesCode: 'S', baselineCode: 'BL-2', reason: '验收' })
    const snapshotBefore = await (await admin.request.get(`/api/v1/baselines/${baseline.id}`)).json()
    await post(`/api/v1/components/${roots[1].id}/reorder`, { direction: 'Up', reason: '根顺序验收' })
    const machines = []
    for (const name of ['一号机', '二号机']) {
      const machine = await post('/api/v1/machines', { projectId: project.id, serialNumber: 'M-' + randomUUID().slice(0, 8), name, reason: '验收' })
      machines.push(machine)
      await post(`/api/v1/machines/${machine.id}/facts`, { operationType: 'InitialSnapshot', coverage: 'Full', sourceType: 'Manual', reason: '验收', items: components.map((component, i) => ({ componentId: component.id, versionId: versions[i].id, absent: false, knownInstalledAt: null })) })
    }
    await post('/api/v1/machines', { projectId: other.id, serialNumber: 'OTHER-' + randomUUID().slice(0, 8), name: '其他项目机台', reason: '隔离验收' })
    await post(`/api/v1/component-versions/${versions[0].id}/safety`, { state: 'Blocked', reason: '匹配与风险独立验收' })
    page = await admin.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await page.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await page.reload()
    await page.locator('.nav-item').filter({ hasText: '项目' }).click()
    await page.getByRole('button', { name: '测试历史', exact: true }).click()
    await page.locator('.laboratory-history-list article').first().waitFor()
    await page.getByLabel('筛选测试历史组件').selectOption(components[0].id)
    await page.waitForFunction(() => [...document.querySelectorAll('.laboratory-history-list article')].every(node => node.textContent.includes('主控系统程序')))
    assert((await page.locator('.laboratory-history-list article').count()) > 0)
    await page.locator('.ant-modal-close').click()
    await page.locator('.baseline-timeline button').filter({ hasText: 'BL-1' }).click()
    await page.locator('.snapshot-root-column').first().waitFor()
    assert.equal(await page.locator('.snapshot-root-column > .snapshot-root strong').first().innerText(), await page.locator('.root-node strong').first().innerText())
    assert.deepEqual((await (await admin.request.get(`/api/v1/baselines/${baseline.id}`)).json()).items, snapshotBefore.items)
    await page.screenshot({ path: path.join(output, 'project.png'), fullPage: true })
    await page.locator('.nav-item').filter({ hasText: '机台' }).click()
    await page.locator('.machine-list-item').first().waitFor()
    assert.equal(await page.locator('.machine-list-item').count(), 2)
    assert.equal(await page.locator('.machine-list-controls select').count(), 0)
    await page.locator('.nav-item').filter({ hasText: '配置比对' }).click()
    await page.getByLabel('左侧配置').selectOption(machines[0].id)
    assert.equal(await page.getByLabel('右侧配置').locator(`option[value="${draft.id}"]`).count(), 0)
    await page.getByLabel('右侧配置').selectOption(baseline.id)
    await page.locator('.comparison-table tbody tr').first().waitFor()
    assert((await page.locator('.compare-summary').innerText()).includes('版本匹配：匹配'))
    assert((await page.locator('.compare-summary').innerText()).includes('风险：严重'))
    await page.getByRole('button', { name: '交换左右配置' }).click()
    await page.locator('.comparison-table tbody tr').first().waitFor()
    assert.equal(await page.getByLabel('左侧配置').inputValue(), baseline.id)
    await page.getByRole('group', { name: '左侧类型' }).getByRole('button', { name: '机台', exact: true }).click()
    await page.getByLabel('左侧配置').selectOption(machines[0].id)
    await page.getByLabel('右侧配置').selectOption(machines[1].id)
    await page.locator('.comparison-table tbody tr').first().waitFor()
    assert.equal(await page.locator('.comparison-table tbody tr.changed').count(), 0)
    await page.getByRole('checkbox', { name: '只看差异' }).check()
    await page.getByText('没有配置差异。', { exact: true }).waitFor()
    await page.getByRole('checkbox', { name: '只看差异' }).uncheck()
    await page.screenshot({ path: path.join(output, 'compare-desktop.png'), fullPage: true })
    await page.getByRole('group', { name: '左侧类型' }).getByRole('button', { name: '基线', exact: true }).click()
    await page.getByRole('group', { name: '右侧类型' }).getByRole('button', { name: '基线', exact: true }).click()
    await page.getByLabel('左侧配置').selectOption(baseline.id)
    await page.getByLabel('右侧配置').selectOption(draft.id)
    await page.locator('.comparison-table tbody tr').first().waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.screenshot({ path: path.join(output, 'compare-mobile.png'), fullPage: true })
    const userName = 'viewer-' + randomUUID().slice(0, 8)
    const password = randomUUID()
    await post('/api/v1/admin/users', { userName, displayName: '只读验收', password, role: 'Viewer', reason: '只读验收' })
    const viewer = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
    await post('/api/v1/auth/login', { userName, password }, viewer.request)
    const view = await viewer.newPage()
    await view.goto('/')
    await view.evaluate(id => localStorage.setItem('confighub.selected-project-id', id), project.id)
    await view.reload()
    await view.locator('.nav-item').filter({ hasText: '项目' }).click()
    await view.locator('.tree-node').first().click()
    assert.equal(await view.locator('.component-inspector form:visible').count(), 0)
    assert.equal(await view.locator('.component-create-panel:visible').count(), 0)
    assert.equal(await view.getByRole('button', { name: '编辑', exact: true }).count(), 0)
    await view.locator('.nav-item').filter({ hasText: '机台' }).click()
    await view.locator('.machine-list-item').first().click()
    assert.equal(await view.locator('.machine-edit:visible, .machine-create:visible').count(), 0)
    assert.equal(await view.getByRole('button', { name: '设为机台目标' }).count(), 0)
    const denied = await viewer.request.post(`/api/v1/projects/${project.id}/components`, { data: { name: '禁止写入', reason: '权限验收' }, headers: { 'Idempotency-Key': randomUUID() } })
    assert.equal(denied.status(), 403)
    await view.screenshot({ path: path.join(output, 'viewer-machine.png'), fullPage: true })
    await viewer.close()
    assert.deepEqual(errors, [])
    console.log('Project scope UX passed: compact layout, history filter/order, viewer read-only, scoped machines and four comparison directions.')
  } catch (error) {
    if (page) await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true })
    throw error
  } finally {
    for (const id of projects) await post(`/api/v1/projects/${id}/archive`, { reason: '验收完成' }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
